    'before_after_lag_table', 'before_after_behavior_table', '-append');

%% Each post-offset bin versus the pre-onset rate
% "Before" is the mean probability over pre_average_window, not a matched
% lag. Each bin after offset is tested two-sided, so occupancy there can
% be either higher or lower than that before rate. Dots use the
% within-target max-T correction, as in the other bin-wise tests.
n_post_bins = numel(before_after.post_lag);
n_postbin_rows = n_before_after_tests * n_post_bins;
postbin_target = cell(n_postbin_rows, 1);
postbin_group = cell(n_postbin_rows, 1);
postbin_time = zeros(n_postbin_rows, 1);
postbin_probability = zeros(n_postbin_rows, 1);
postbin_pre = zeros(n_postbin_rows, 1);
postbin_difference = zeros(n_postbin_rows, 1);
postbin_p = zeros(n_postbin_rows, 1);
postbin_group_p = zeros(n_postbin_rows, 1);
postbin_target_p = zeros(n_postbin_rows, 1);
row_n = 0;
for target_n = 1:numel(before_after.target_names)
    for group_n = 1:numel(before_after.group_names)
        for bin_n = 1:n_post_bins
            row_n = row_n + 1;
            time_index = before_after.post_index(bin_n);
            postbin_target{row_n} = before_after.target_names{target_n};
            postbin_group{row_n} = before_after.group_names{group_n};
            postbin_time(row_n) = before_after.post_lag(bin_n);
            postbin_probability(row_n) = ...
                before_after.probability(group_n, target_n, time_index);
            postbin_pre(row_n) = before_after.pre_probability(group_n, target_n);
            postbin_difference(row_n) = ...
                before_after.observed_postbin_minus_pre(group_n, bin_n, target_n);
            postbin_p(row_n) = ...
                before_after.p_value_postbin_vs_pre(group_n, bin_n, target_n);
            postbin_group_p(row_n) = ...
                before_after.p_value_postbin_vs_pre_fwer_group( ...
                group_n, bin_n, target_n);
            postbin_target_p(row_n) = ...
                before_after.p_value_postbin_vs_pre_fwer_target( ...
                group_n, bin_n, target_n);
        end
    end
end
postbin_versus_pre_table = table(postbin_target, postbin_group, ...
    postbin_time, postbin_probability, postbin_pre, postbin_difference, ...
    postbin_p, postbin_group_p, postbin_target_p, ...
    'VariableNames', {'Target', 'BehaviorGroup', 'SecondsAfterOffset', ...
    'PostBinProbability', 'PreOnsetProbability', 'PostBinMinusPre', ...
    'PermutationP', 'GroupMaxTP', 'TargetMaxTP'});

post_x = before_after.wrapped_plot_time(before_after.post_index);
figure_handle = figure('Visible', 'off', 'Color', 'w', ...
    'Position', [80 80 1100 900]);
for group_n = 1:numel(before_after.group_names)
    for target_n = 1:numel(before_after.target_names)
        subplot(numel(before_after.group_names), ...
            numel(before_after.target_names), ...
            (group_n - 1) * numel(before_after.target_names) + target_n);
        hold on
        patch([before_after.pre_average_window(1), 0, 0, ...
            before_after.pre_average_window(1)], [0 0 1 1], ...
            [0.85 0.85 0.85], 'EdgeColor', 'none', ...
            'FaceAlpha', 0.35, 'HandleVisibility', 'off');
        patch(flank_seconds + [0, flank_seconds, flank_seconds, 0], ...
            [0 0 1 1], [0.85 0.85 0.85], 'EdgeColor', 'none', ...
            'FaceAlpha', 0.45, 'HandleVisibility', 'off');
        curve = reshape(before_after.probability(group_n, target_n, :), ...
            1, []);
        curve(before_after.pre_index) = movmean( ...
            curve(before_after.pre_index), smooth_bins);
        curve(before_after.post_index) = movmean( ...
            curve(before_after.post_index), smooth_bins);
        pre_level = before_after.pre_probability(group_n, target_n);
        plot(plot_time([1 end]), pre_level * [1 1], ':', ...
            'Color', [0.25 0.25 0.25], 'LineWidth', 1.2, ...
            'DisplayName', 'Mean before onset');
        plot(plot_time, curve, 'Color', colors(target_n, :), ...
            'LineWidth', 1.8, 'DisplayName', 'Probability');
        significant = reshape( ...
            before_after.p_value_postbin_vs_pre_fwer_target( ...
            group_n, :, target_n), 1, []) < before_after.significance_alpha;
        if any(significant)
            plot(post_x(significant), ...
                0.97 * ones(1, sum(significant)), 'k.', ...
                'MarkerSize', 10, 'HandleVisibility', 'off');
        end
        plot([0 0], [0 1], 'k--', 'HandleVisibility', 'off');
        plot(flank_seconds * [1 1], [0 1], 'k--', 'HandleVisibility', 'off');
        xlim(plot_time([1 end]));
        ylim([0 1]);
        ylabel('Probability');
        if group_n == numel(before_after.group_names)
            xlabel(['Seconds before onset | warped bout (0 to T) | ' ...
                'seconds after offset']);
        end
        title(sprintf('%s | %s\nmean before %.3f', ...
            before_after.target_names{target_n}, ...
            before_after.group_names{group_n}, pre_level));
        if group_n == 1 && target_n == 1
            legend('Location', 'best');
        end
    end
end
sgtitle(sprintf(['Two-sided post-offset bins vs mean before rate ' ...
