        imagesc(plot_time, 1:numel(before_after.behavior_types), map);
        axis xy
        hold on
        plot([0 0], [0.5 numel(before_after.behavior_types) + 0.5], ...
            'w--', 'LineWidth', 1);
        plot(flank_seconds * [1 1], ...
            [0.5 numel(before_after.behavior_types) + 0.5], ...
            'w--', 'LineWidth', 1);
        yticks(1:numel(before_after.behavior_types));
        yticklabels(before_after.behavior_types);
        caxis([0 1]);
        colorbar
        title(sprintf('%s, %s (N=%d)', ...
            before_after.target_names{target_n}, map_actors{actor_n}, ...
