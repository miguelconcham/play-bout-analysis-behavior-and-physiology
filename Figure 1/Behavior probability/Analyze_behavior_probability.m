        xlabel('Before | warped bout | after');
    end
end
sgtitle(sprintf(['Behavior probability on the time-wrapped axis; ' ...
    'T = %g s; %d warp bins'], flank_seconds, before_after.wrapped_bins));
map_base = fullfile(default_parameters.output_folder, ...
    ['behavior_before_after_maps_', before_after_tag]);
savefig(figure_handle, [map_base, '.fig']);
