close(figure_handle);

%% Compare two target behaviors after pooling all sessions
% Both names must have been included in target_behaviors when running
% Estimate_behavior_probability.m.
behavior_pair = {'Pounce', 'PounceI'};
comparison_options = struct();
% Choose 'self', 'partner', or 'either'. 'either' is present when the
% behavior was performed by the target animal or its partner.
comparison_options.actor_relation = 'either';
% The permutation statistic is the difference in mean occupancy across
% this offset-relative window. Full unsmoothed time courses are retained.
if isfield(loaded, 'analysis_parameters') && ...
        isfield(loaded.analysis_parameters, 'comparison_window') && ...
        ~isempty(loaded.analysis_parameters.comparison_window)
    comparison_options.test_window = ...
        loaded.analysis_parameters.comparison_window;
else
    comparison_options.test_window = [0 2];
    warning('Analyze_behavior_probability:ComparisonWindow', ...
        ['Saved Estimate parameters have no comparison_window. Using ' ...
        '[0 2] s; re-run Estimate to define the gray area there.']);
end
comparison_options.n_permutations = 10000;
comparison_options.random_seed = 1;
plot_smoothing_seconds = 0.10;

comparison = compare_behavior_pair_probability( ...
    loaded.recordings, behavior_pair, comparison_options);
comparison_table = table(comparison.group_names(:), ...
    comparison.observed_difference(:), comparison.p_value(:), ...
    comparison.p_value_holm(:), ...
    'VariableNames', {'BehaviorGroup', 'ProbabilityDifference', ...
    'PermutationP', 'HolmP'});
disp(comparison_table);
n_test_bins = numel(comparison.test_time);
comparison_bin_table = table( ...
    repmat(comparison.group_names(:), n_test_bins, 1), ...
    repelem(comparison.test_time(:), numel(comparison.group_names)), ...
    comparison.observed_difference_by_bin(:), ...
    comparison.p_value_by_bin(:), ...
    comparison.p_value_by_bin_fwer_group(:), ...
    comparison.p_value_by_bin_fwer_all(:), ...
    'VariableNames', {'BehaviorGroup', 'Time', ...
    'ProbabilityDifference', 'PermutationP', ...
    'GroupMaxTP', 'GlobalMaxTP'});
pair_tag = sprintf('%s_vs_%s', comparison.behavior_pair{:});

figure_handle = figure('Visible', 'off', 'Color', 'w', ...
    'Position', [100 100 900 1000]);
colors = lines(2);
smooth_bins = max(1, round(plot_smoothing_seconds / analysis.bin_size));
for group_n = 1:numel(comparison.group_names)
    subplot(3, 1, group_n);
    hold on
    patch(comparison.test_window([1 2 2 1]), [0 0 1 1], ...
        [0.85 0.85 0.85], 'EdgeColor', 'none', ...
        'FaceAlpha', 0.35, 'HandleVisibility', 'off');
    for target_n = 1:2
        curve = reshape(comparison.probability(group_n, target_n, :), ...
            1, []);
        curve = movmean(curve, smooth_bins);
        plot(comparison.time, curve, 'Color', colors(target_n, :), ...
            'LineWidth', 1.8, 'DisplayName', sprintf('%s (N=%d)', ...
            comparison.behavior_pair{target_n}, ...
            comparison.n_events_plot(target_n)));
    end
    significant = comparison.p_value_by_bin_fwer_all(group_n, :) < ...
        comparison.bin_significance_alpha;
    if any(significant)
        plot(comparison.test_time(significant), ...
            0.97 * ones(1, sum(significant)), 'k.', ...
            'MarkerSize', 10, 'HandleVisibility', 'off');
    end
    plot([0 0], [0 1], 'k--', 'HandleVisibility', 'off');
    xlim(comparison.time([1 end]));
    ylim([0 1]);
    ylabel('Probability');
    title(sprintf('%s: permutation p = %.4g, Holm p = %.4g', ...
        comparison.group_names{group_n}, comparison.p_value(group_n), ...
        comparison.p_value_holm(group_n)));
    legend('Location', 'best');
end
xlabel('Time from target behavior offset (s)');
sgtitle(sprintf(['Grouped behavior probability (%s); test [%g, %g] s ' ...
    '(strictly post-offset); ' ...
    '%d shared sessions; %.2f s display smoothing; ' ...
    'black dots: global max-T p < %.2f'], ...
    comparison.actor_relation, comparison.test_time([1 end]), ...
    comparison.n_eligible_sessions, plot_smoothing_seconds, ...
    comparison.bin_significance_alpha));

figure_base = fullfile(default_parameters.output_folder, ...
    ['behavior_group_probability_', pair_tag]);
savefig(figure_handle, [figure_base, '.fig']);
saveas(figure_handle, [figure_base, '.png']);
close(figure_handle);
writetable(comparison_bin_table, fullfile(default_parameters.output_folder, ...
    ['behavior_group_binwise_', pair_tag, '.csv']));

save(analysis_file, 'comparison', 'comparison_table', ...
    'comparison_bin_table', '-append');

%% Before onset versus after offset, on a time-wrapped axis
% Pre and post stay in real time. The bout from onset to offset is
% resampled into a fixed bin count so events of different durations share
% one axis. The before probability is the mean inside pre_average_window,
% in seconds relative to onset. Differences use that mean. Leave it empty
% to average the whole stored pre-onset flank, (-T, 0). The window must
% lie inside that flank.
before_after_targets = {'Pounce', 'PounceI'};
pre_average_window = [];
before_after_options = struct();
before_after_options.actor_relation = 'either';
before_after_options.n_permutations = 10000;
before_after_options.random_seed = 1;
before_after_options.pre_average_window = pre_average_window;

before_after = compare_behavior_before_after_probability( ...
    loaded.recordings, before_after_targets, before_after_options);
n_before_after_tests = numel(before_after.p_value);
before_after_target = cell(n_before_after_tests, 1);
before_after_group = cell(n_before_after_tests, 1);
row_n = 0;
for target_n = 1:numel(before_after.target_names)
    for group_n = 1:numel(before_after.group_names)
        row_n = row_n + 1;
        before_after_target{row_n} = before_after.target_names{target_n};
        before_after_group{row_n} = before_after.group_names{group_n};
    end
end
before_after_table = table(before_after_target, before_after_group, ...
    before_after.pre_probability(:), before_after.post_probability(:), ...
    before_after.observed_difference(:), before_after.p_value(:), ...
    before_after.p_value_holm(:), ...
    repelem(before_after.n_events_test(:), ...
    numel(before_after.group_names)), ...
    'VariableNames', {'Target', 'BehaviorGroup', 'PreProbability', ...
    'PostProbability', 'PostMinusPre', 'PermutationP', 'HolmP', ...
    'NEvents'});
disp(before_after_table);

n_lags = numel(before_after.lag_seconds);
n_lag_rows = n_before_after_tests * n_lags;
lag_target = cell(n_lag_rows, 1);
lag_group = cell(n_lag_rows, 1);
lag_time = zeros(n_lag_rows, 1);
lag_difference = zeros(n_lag_rows, 1);
lag_p = zeros(n_lag_rows, 1);
lag_group_p = zeros(n_lag_rows, 1);
lag_target_p = zeros(n_lag_rows, 1);
row_n = 0;
for target_n = 1:numel(before_after.target_names)
    for group_n = 1:numel(before_after.group_names)
        for lag_n = 1:n_lags
            row_n = row_n + 1;
            lag_target{row_n} = before_after.target_names{target_n};
            lag_group{row_n} = before_after.group_names{group_n};
            lag_time(row_n) = before_after.lag_seconds(lag_n);
            lag_difference(row_n) = ...
                before_after.observed_difference_by_lag(group_n, lag_n, target_n);
            lag_p(row_n) = before_after.p_value_by_lag(group_n, lag_n, target_n);
            lag_group_p(row_n) = ...
                before_after.p_value_by_lag_fwer_group(group_n, lag_n, target_n);
            lag_target_p(row_n) = ...
                before_after.p_value_by_lag_fwer_target(group_n, lag_n, target_n);
        end
    end
end
before_after_lag_table = table(lag_target, lag_group, lag_time, ...
    lag_difference, lag_p, lag_group_p, lag_target_p, ...
    'VariableNames', {'Target', 'BehaviorGroup', 'LagSeconds', ...
    'PostMinusPre', 'PermutationP', 'GroupMaxTP', 'TargetMaxTP'});

n_behavior_rows = numel(before_after.behavior_types) * ...
    numel(before_after.target_names);
behavior_target = cell(n_behavior_rows, 1);
behavior_name = cell(n_behavior_rows, 1);
behavior_pre = zeros(n_behavior_rows, 1);
behavior_post = zeros(n_behavior_rows, 1);
row_n = 0;
for target_n = 1:numel(before_after.target_names)
    for behavior_n = 1:numel(before_after.behavior_types)
        row_n = row_n + 1;
        behavior_target{row_n} = before_after.target_names{target_n};
        behavior_name{row_n} = before_after.behavior_types{behavior_n};
        behavior_pre(row_n) = ...
            before_after.behavior_pre_probability(behavior_n, target_n);
        behavior_post(row_n) = ...
            before_after.behavior_post_probability(behavior_n, target_n);
    end
end
before_after_behavior_table = table(behavior_target, behavior_name, ...
    behavior_pre, behavior_post, ...
    'VariableNames', {'Target', 'Behavior', 'PreProbability', ...
    'PostProbability'});

flank_seconds = before_after.flank_seconds;
plot_time = before_after.wrapped_plot_time;
pre_x = plot_time(before_after.pre_index);
post_x = plot_time(before_after.post_index);
matched_pre_x = pre_x(end:-1:1);
smooth_bins = max(1, round(plot_smoothing_seconds / analysis.bin_size));
figure_handle = figure('Visible', 'off', 'Color', 'w', ...
    'Position', [80 80 1100 900]);
for group_n = 1:numel(before_after.group_names)
    for target_n = 1:numel(before_after.target_names)
        subplot(numel(before_after.group_names), ...
            numel(before_after.target_names), ...
            (group_n - 1) * numel(before_after.target_names) + target_n);
        hold on
        patch([before_after.pre_average_window(1), 0, 0, ...
            before_after.pre_average_window(1)], [0 0 1 1], ...
            [0.85 0.85 0.85], 'EdgeColor', 'none', ...
            'FaceAlpha', 0.35, 'HandleVisibility', 'off');
        patch(flank_seconds + [0, flank_seconds, flank_seconds, 0], ...
            [0 0 1 1], [0.85 0.85 0.85], 'EdgeColor', 'none', ...
            'FaceAlpha', 0.35, 'HandleVisibility', 'off');
        curve = reshape(before_after.probability(group_n, target_n, :), ...
            1, []);
        curve(before_after.pre_index) = movmean( ...
            curve(before_after.pre_index), smooth_bins);
        curve(before_after.post_index) = movmean( ...
            curve(before_after.post_index), smooth_bins);
        plot(plot_time, curve, 'Color', colors(target_n, :), ...
            'LineWidth', 1.8);
        significant = reshape( ...
            before_after.p_value_by_lag_fwer_target(group_n, :, target_n), ...
            1, []) < before_after.significance_alpha;
        if any(significant)
            plot(matched_pre_x(significant), ...
                0.97 * ones(1, sum(significant)), 'k.', ...
                'MarkerSize', 10, 'HandleVisibility', 'off');
            plot(post_x(significant), ...
                0.97 * ones(1, sum(significant)), 'k.', ...
                'MarkerSize', 10, 'HandleVisibility', 'off');
        end
        plot([0 0], [0 1], 'k--', 'HandleVisibility', 'off');
        plot(flank_seconds * [1 1], [0 1], 'k--', 'HandleVisibility', 'off');
        xlim(plot_time([1 end]));
        ylim([0 1]);
        ylabel('Probability');
        if group_n == numel(before_after.group_names)
            xlabel(['Seconds before onset | warped bout (0 to T) | ' ...
                'seconds after offset']);
        end
        title(sprintf(['%s | %s\npre %.3f, post %.3f, p = %.4g, ' ...
            'Holm p = %.4g'], ...
            before_after.target_names{target_n}, ...
            before_after.group_names{group_n}, ...
            before_after.pre_probability(group_n, target_n), ...
            before_after.post_probability(group_n, target_n), ...
            before_after.p_value(group_n, target_n), ...
            before_after.p_value_holm(group_n, target_n)));
    end
end
sample_note = cell(1, numel(before_after.target_names));
for target_n = 1:numel(before_after.target_names)
    sample_note{target_n} = sprintf('%s %d/%d events, %d sessions', ...
        before_after.target_names{target_n}, ...
        before_after.n_events_test(target_n), ...
        before_after.n_events_available(target_n), ...
        before_after.n_sessions(target_n));
end
sgtitle(sprintf(['Before vs after (%s); before averaged over [%g, %g] s; ' ...
    'T = %g s; %d warp bins; post minus pre; gray = averaged before ' ...
    'window and post flank; black dots: within-target max-T p < %.2f; %s'], ...
    before_after.actor_relation, before_after.pre_average_window, ...
    flank_seconds, before_after.wrapped_bins, ...
    before_after.significance_alpha, strjoin(sample_note, '; ')));

before_after_tag = strjoin(before_after.target_names, '_vs_');
figure_base = fullfile(default_parameters.output_folder, ...
    ['behavior_before_after_', before_after_tag]);
savefig(figure_handle, [figure_base, '.fig']);
saveas(figure_handle, [figure_base, '.png']);
close(figure_handle);

figure_handle = figure('Visible', 'off', 'Color', 'w', ...
    'Position', [80 80 1100 800]);
map_sets = {before_after.behavior_probability_self, ...
    before_after.behavior_probability_partner};
map_actors = {'Target performer (self)', 'Other animal (partner)'};
for actor_n = 1:2
    for target_n = 1:numel(before_after.target_names)
        subplot(2, numel(before_after.target_names), ...
            (actor_n - 1) * numel(before_after.target_names) + target_n);
        map = reshape(map_sets{actor_n}(:, target_n, :), ...
