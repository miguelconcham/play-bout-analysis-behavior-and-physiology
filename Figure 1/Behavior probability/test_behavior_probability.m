function test_behavior_probability()
%TEST_BEHAVIOR_PROBABILITY Checks using synthetic behavior annotations.

this_dir = fileparts(mfilename('fullpath'));
if ~isempty(this_dir)
    addpath(this_dir);
end

Animal = { ...
    'Session_structure'; 'RatA'; 'RatB'; 'RatA'; 'RatB'; 'RatA'; ...
    'Session_structure'; 'RatC'; 'RatA'};
Start = [0; 1; 1.99; 1.90; 3; 3.99; 20; 21; 21.90];
End = [10; 2; 2.02; 2.10; 4; 4.01; 30; 22; 22.10];
Length = End - Start;
Type = { ...
    'Partners session'; 'Pounce_A'; 'Bite'; 'Grooming'; 'Bite'; ...
    'Sniffing'; 'Partners session'; 'Bite'; 'Scratch'};
behavior = table(Animal, Start, End, Length, Type);

options = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce', 'Bite'}}, ...
    'time_window', [-0.1 0.1], ...
    'bin_size', 0.1));
window_options = behavior_probability_options(struct( ...
    'time_window', [-1 3], ...
    'comparison_window', [0 1]));
assert(isequal(window_options.comparison_window, [0 1]), ...
    'The Estimate-defined gray comparison window was not retained.');
invalid_window_failed = false;
try
    behavior_probability_options(struct( ...
        'time_window', [-1 1], 'bin_size', 0.1, ...
        'comparison_window', [0 0.05]));
catch exception
    invalid_window_failed = strcmp(exception.identifier, ...
        'behavior_probability_options:ComparisonWindowBins');
end
assert(invalid_window_failed, ...
    'A gray area without a sampled post-offset bin was accepted.');
recording = GENERATE_BEHAVIOR_PROBABILITY(behavior, 'RatA', options);

assert(numel(recording.sessions) == 2, ...
    'The two partner-play sessions were not retained separately.');
assert(isequal(recording.time, [-0.1 0 0.1]), ...
    'The requested offset-relative bins changed.');
assert(isequal(size(recording.sessions(1).self_behavior), [3 14 3]), ...
    'Session 1 does not have target x behavior x time dimensions.');
assert(isequal(size(recording.sessions(2).self_behavior), [1 14 3]), ...
    'Session 2 target count is wrong.');

pounce = find(strcmp(recording.behavior_types, 'Pounce'));
bite = find(strcmp(recording.behavior_types, 'Bite'));
grooming = find(strcmp(recording.behavior_types, 'Grooming'));
sniffing = find(strcmp(recording.behavior_types, 'Sniffing'));
scratching = find(strcmp(recording.behavior_types, 'Scratching'));
zero_bin = find(recording.time == 0);

first_session = recording.sessions(1);
pounce_event = find(strcmp(first_session.target_behavior, 'Pounce'));
bite_event = find(abs(first_session.target_offset - 4) < 1e-12);
assert(first_session.self_behavior(pounce_event, pounce, zero_bin), ...
    'Pounce_A was not normalized to self Pounce at its offset.');
assert(first_session.self_behavior(pounce_event, grooming, zero_bin), ...
    'Concurrent self Grooming was not represented.');
assert(first_session.partner_behavior(pounce_event, bite, zero_bin), ...
    'Concurrent partner Bite was not represented.');
assert(strcmp(first_session.target_actor{bite_event}, 'RatB'), ...
    'The partner-performed target was not retained.');
assert(first_session.self_behavior(bite_event, bite, zero_bin), ...
    'Self did not follow the target performer for a partner target.');
assert(first_session.partner_behavior(bite_event, sniffing, zero_bin), ...
    'The focal animal was not treated as partner to a partner target.');

second_session = recording.sessions(2);
assert(strcmp(second_session.target_actor{1}, 'RatC'), ...
    'The second session target actor is wrong.');
assert(second_session.partner_behavior(1, scratching, zero_bin), ...
    'Scratch was not normalized to partner Scratching.');

pounce_only = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce'}}, ...
    'time_window', [-0.1 0.1], ...
    'bin_size', 0.1));
pounce_recording = GENERATE_BEHAVIOR_PROBABILITY( ...
    behavior, 'RatA', pounce_only);
assert(size(pounce_recording.sessions(1).self_behavior, 1) == 1, ...
    'Single-target selection did not keep the Pounce event.');
assert(isequal(size(pounce_recording.sessions(2).self_behavior), [0 14 3]), ...
    'A session without a selected target did not retain an empty matrix.');

% A window from one session must not include behavior in the next session.
boundary_behavior = table( ...
    {'Session_structure'; 'RatA'; 'Session_structure'; 'RatA'}, ...
    [0; 0.8; 1; 1.0], [1; 0.9; 2; 1.2], ...
    [1; 0.1; 1; 0.2], ...
    {'Partners session'; 'Pounce_A'; 'Partners session'; 'Grooming'}, ...
    'VariableNames', {'Animal', 'Start', 'End', 'Length', 'Type'});
boundary_options = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce'}}, ...
    'time_window', [-0.1 0.2], ...
    'bin_size', 0.1));
boundary_recording = GENERATE_BEHAVIOR_PROBABILITY( ...
    boundary_behavior, 'RatA', boundary_options);
boundary_grooming = find(strcmp( ...
    boundary_recording.behavior_types, 'Grooming'));
assert(~any(boundary_recording.sessions(1).self_behavior( ...
    1, boundary_grooming, :), 'all'), ...
    'Behavior from the next play session leaked into the first matrix.');

analysis = summarize_behavior_probability(recording);
assert(analysis.n_sessions_total == 2 && ...
    analysis.n_sessions_with_targets == 2, ...
    'Per-session probability summary lost a play session.');
assert(analysis.total_target_events == 4, ...
    'The pooled target-event count is wrong.');
expected = 1 / 4;
assert(abs(analysis.event_weighted_partner(scratching, zero_bin) - ...
    expected) < 1e-12, ...
    'Event-weighted behavior probability is wrong.');

comparison_options = struct( ...
    'actor_relation', 'either', ...
    'test_window', [0 0.2], ...
    'n_permutations', 99, ...
    'random_seed', 7);
comparison_extra = table( ...
    {'RatC'; 'Session_structure'; 'RatD'; 'RatD'}, ...
    [23; 40; 41; 42.05], [24; 50; 42; 42.10], ...
    [1; 10; 1; 0.05], ...
    {'Pounce_B'; 'Partners session'; 'Bite'; 'Grooming'}, ...
    'VariableNames', {'Animal', 'Start', 'End', 'Length', 'Type'});
comparison_generation_options = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce', 'Bite'}}, ...
    'time_window', [-0.1 0.2], ...
    'bin_size', 0.1, ...
    'comparison_window', [0 0.2]));
comparison_recording = GENERATE_BEHAVIOR_PROBABILITY( ...
    [behavior; comparison_extra], 'RatA', comparison_generation_options);
comparison = compare_behavior_pair_probability( ...
    comparison_recording, {'Pounce', 'Bite'}, comparison_options);
assert(isequal(size(comparison.probability), [3 2 4]), ...
    'Grouped probability does not have group x target x time dimensions.');
assert(isequal(comparison.n_events_plot, [2 3]), ...
    'Pooled plotting event counts are wrong.');
assert(comparison.n_eligible_sessions == 2 && ...
    isequal(comparison.n_events_test, [2 3]), ...
    'The stratified test did not retain only sessions with both targets.');
assert(isequal(comparison.n_events_all_sessions, [2 4]), ...
    'The all-session event counts did not retain the single-target session.');
assert(comparison.probability(1, 1, zero_bin) == 1, ...
    'The Pounce target did not produce play probability at time zero.');
assert(comparison.probability(2, 2, zero_bin) == 1, ...
    'Bite targets did not produce aggressive probability at time zero.');
first_test_bin = find(abs(comparison.time - 0.1) < 1e-12);
assert(comparison.probability_all_sessions(3, 2, first_test_bin) > ...
    comparison.probability(3, 2, first_test_bin), ...
    'Eligible-session and all-session descriptive curves were conflated.');
assert(abs(comparison.observed_difference(3) - 1 / 12) < 1e-12, ...
    'The pooled post-offset exploratory difference is wrong.');
expected_bin_difference = zeros(3, 2);
expected_bin_difference(3, 1) = 1 / 6;
assert(isequal(size(comparison.observed_difference_by_bin), [3 2]) && ...
    max(abs(comparison.observed_difference_by_bin - ...
    expected_bin_difference), [], 'all') < 1e-12, ...
    'Bin-wise probability differences are incorrectly shaped or ordered.');
assert(all(comparison.p_value_by_bin(:, 2) == 1) && ...
    abs(comparison.p_value_by_bin(3, 1) - comparison.p_value(3)) < 1e-12, ...
    'Hand-verifiable bin-wise permutation p-values are wrong.');
assert(all(comparison.p_value_by_bin_fwer_group(:) >= ...
    comparison.p_value_by_bin(:)) && ...
    all(comparison.p_value_by_bin_fwer_all(:) >= ...
    comparison.p_value_by_bin_fwer_group(:)), ...
    'Bin-wise max-T correction reduced a p-value.');
expected_exploratory_null = [-1/3 1/12 1/2];
null_distance = min(abs(comparison.null_difference(:, 3) - ...
    expected_exploratory_null), [], 2);
assert(all(abs(comparison.null_difference(:, 1:2)) < 1e-12, 'all') && ...
    all(null_distance < 1e-12), ...
    'Permutation outcomes do not preserve the within-session label counts.');
assert(all(comparison.p_value >= 0 & comparison.p_value <= 1) && ...
    all(comparison.p_value_holm >= comparison.p_value), ...
    'Permutation or Holm-adjusted p-values are invalid.');
[sorted_p, sorted_order] = sort(comparison.p_value);
expected_holm_sorted = cummax((3:-1:1) .* sorted_p);
expected_holm = nan(size(expected_holm_sorted));
expected_holm(sorted_order) = min(1, expected_holm_sorted);
assert(max(abs(comparison.p_value_holm - expected_holm)) < 1e-12, ...
    'Holm correction is wrong.');
comparison_repeat = compare_behavior_pair_probability( ...
    comparison_recording, {'Pounce', 'Bite'}, comparison_options);
assert(isequal(comparison.null_difference, ...
    comparison_repeat.null_difference), ...
    'The permutation result is not reproducible for a fixed seed.');
assert(isequal(comparison.p_value_by_bin_fwer_all, ...
    comparison_repeat.p_value_by_bin_fwer_all), ...
    'Bin-wise permutation results are not reproducible for a fixed seed.');

defaults = behavior_probability_options();
assert(defaults.wrapped_bins == 20 && defaults.flank_seconds == 2 && ...
    numel(defaults.pre_lag) == 200 && numel(defaults.post_lag) == 200 && ...
    all(defaults.pre_lag < 0) && all(defaults.post_lag > 0) && ...
    all(diff(defaults.wrapped_plot_time) > 0), ...
    'The default time-wrapped axis is not 2 s flanks plus 20 bout bins.');
invalid_flank_failed = false;
try
    behavior_probability_options(struct( ...
        'flank_seconds', 0.15, 'bin_size', 0.1));
catch exception
    invalid_flank_failed = strcmp(exception.identifier, ...
        'behavior_probability_options:FlankBins');
end
assert(invalid_flank_failed, ...
    'A flank that is not a multiple of bin_size was accepted.');

wrap_behavior = table( ...
    {'Session_structure'; 'RatA'; 'RatA'; 'RatA'; 'RatA'; ...
    'RatB'; 'RatB'; 'RatB'; 'RatB'; 'Session_structure'; 'RatA'}, ...
    [0; 2; 1.75; 5; 6.05; 8; 9.05; 11; 12.05; 30; 30.05], ...
    [20; 3; 2; 6; 6.25; 9; 9.30; 12; 12.25; 40; 30.40], ...
    [20; 1; 0.25; 1; 0.20; 1; 0.25; 1; 0.20; 10; 0.35], ...
    {'Partners session'; 'Pounce_A'; 'Grooming'; 'Pounce_A'; 'Sniffing'; ...
    'Pounce_Ai'; 'Bite'; 'Pounce_Bi'; 'Bite'; 'Partners session'; ...
    'Pounce_A'}, ...
    'VariableNames', {'Animal', 'Start', 'End', 'Length', 'Type'});
wrap_options = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce', 'PounceI'}}, ...
    'time_window', [-0.2 0.2], ...
    'bin_size', 0.1, ...
    'flank_seconds', 0.2, ...
    'wrapped_bins', 4));
wrap_recording = GENERATE_BEHAVIOR_PROBABILITY( ...
    wrap_behavior, 'RatA', wrap_options);
assert(numel(wrap_recording.pre_index) == 2 && ...
    numel(wrap_recording.wrap_index) == 4 && ...
    numel(wrap_recording.post_index) == 2 && ...
    numel(wrap_recording.wrapped_plot_time) == 8, ...
    'The wrapped axis does not have pre, bout, and post blocks.');
assert(all(diff(wrap_recording.wrapped_plot_time) > 0) && ...
    wrap_recording.wrapped_plot_time(wrap_recording.wrap_index(1)) == 0 && ...
    wrap_recording.wrapped_plot_time(wrap_recording.wrap_index(end)) == 0.2, ...
    'Onset and offset are not the ends of the warped block.');

first_wrap = wrap_recording.sessions(1);
pounce_rows = find(strcmp(first_wrap.target_behavior, 'Pounce'));
[~, pounce_order] = sort(first_wrap.target_offset(pounce_rows));
pounce_rows = pounce_rows(pounce_order);
pounce_type = find(strcmp(wrap_recording.behavior_types, 'Pounce'));
grooming_type = find(strcmp(wrap_recording.behavior_types, 'Grooming'));
sniffing_type = find(strcmp(wrap_recording.behavior_types, 'Sniffing'));
pre_bins = wrap_recording.pre_index;
wrap_bins = wrap_recording.wrap_index;
post_bins = wrap_recording.post_index;
assert(all(first_wrap.wrapped_in_session(pounce_rows, :), 'all'), ...
    'A fully interior bout was marked outside the Partners session.');
assert(~any(first_wrap.self_behavior_wrapped( ...
    pounce_rows(1), pounce_type, pre_bins)) && ...
    all(first_wrap.self_behavior_wrapped( ...
    pounce_rows(1), pounce_type, wrap_bins)) && ...
    ~any(first_wrap.self_behavior_wrapped( ...
    pounce_rows(1), pounce_type, post_bins)), ...
    'Pounce was not confined to the warped onset-offset block.');
assert(all(first_wrap.self_behavior_wrapped( ...
    pounce_rows(1), grooming_type, pre_bins)) && ...
    ~any(first_wrap.self_behavior_wrapped( ...
    pounce_rows(1), grooming_type, post_bins)), ...
    'Pre-onset grooming was not kept on the real-time pre flank.');
assert(all(first_wrap.self_behavior_wrapped( ...
    pounce_rows(2), sniffing_type, post_bins)) && ...
    ~any(first_wrap.self_behavior_wrapped( ...
    pounce_rows(2), sniffing_type, pre_bins)), ...
    'Post-offset sniffing was not kept on the real-time post flank.');
assert(~all(wrap_recording.sessions(2).wrapped_in_session(1, pre_bins)), ...
    'A pre-onset flank that leaves the Partners session was kept.');

before_after_options = struct( ...
    'actor_relation', 'either', ...
    'n_permutations', 199, ...
    'random_seed', 7);
before_after = compare_behavior_before_after_probability( ...
    wrap_recording, {'Pounce', 'PounceI'}, before_after_options);
assert(isequal(before_after.n_events_available, [3 2]) && ...
    isequal(before_after.n_events_test, [2 2]) && ...
    isequal(before_after.n_sessions, [1 1]), ...
    'Incomplete flanks were not dropped from the before-versus-after test.');
assert(isequal(size(before_after.probability), [3 2 8]), ...
    'Wrapped group probability does not have group x target x time size.');
play_wrap = before_after.probability(1, 1, wrap_bins);
assert(all(abs(play_wrap(:) - 1) < 1e-12), ...
    'Play probability is not 1 across the warped Pounce bout.');
assert(abs(before_after.pre_probability(3, 1) - 0.5) < 1e-12 && ...
    abs(before_after.post_probability(3, 1) - 0.5) < 1e-12 && ...
    abs(before_after.observed_difference(3, 1)) < 1e-12, ...
    'Pounce exploratory before/after probabilities are wrong.');
assert(all(abs(before_after.observed_difference(1:2, 1)) < 1e-12) && ...
    all(before_after.p_value(:, 1) == 1), ...
    'A zero before/after difference did not get permutation p = 1.');
assert(abs(before_after.pre_probability(2, 2)) < 1e-12 && ...
    abs(before_after.post_probability(2, 2) - 1) < 1e-12 && ...
    abs(before_after.observed_difference(2, 2) - 1) < 1e-12, ...
    'PounceI aggressive post-minus-pre difference is not 1.');
assert(all(abs(before_after.observed_difference_by_lag(2, :, 2) - 1) < ...
    1e-12) && ...
    max(abs(before_after.p_value_by_lag(2, :, 2) - ...
    before_after.p_value(2, 2))) < 1e-12, ...
    'Matched pre/post lags do not follow the window difference.');
aggressive_null = before_after.null_difference{2}(:, 2);
assert(all(abs(aggressive_null - round(aggressive_null)) < 1e-12) && ...
    all(ismember(round(aggressive_null), [-1 0 1])) && ...
    min(aggressive_null) == -1 && max(aggressive_null) == 1, ...
    'PounceI sign flips are not the two-event paired null.');
assert(before_after.p_value(2, 2) < 1 && ...
    all(before_after.p_value_holm(:) >= before_after.p_value(:)) && ...
    all(before_after.p_value_by_lag_fwer_target(:) >= ...
    before_after.p_value_by_lag(:)), ...
    'Before/after p-values or their corrections are invalid.');
assert(isequal(size(before_after.observed_postbin_minus_pre), [3 2 2]) && ...
    all(abs(before_after.observed_postbin_minus_pre(2, :, 2) - 1) < 1e-12), ...
    'Post-bin minus whole-pre-flank difference is wrong for PounceI.');
assert(all(before_after.p_value_postbin_vs_pre(1:2, :, 1) == 1) && ...
    all(abs(before_after.observed_postbin_minus_pre(3, :, 1)) < 1e-12), ...
    'A post bin equal to the pre-onset rate was not handled.');
exploratory_null = before_after.null_difference{1}(:, 3);
expected_onesided = (1 + sum(exploratory_null >= 0)) / ...
    (before_after.n_permutations + 1);
assert(max(abs(before_after.p_value_postbin_vs_pre(3, :, 1) - ...
    expected_onesided)) < 1e-12, ...
    'One-sided post-bin p-values do not use the pre-onset mean.');
assert(all(before_after.p_value_postbin_vs_pre(2, :, 2) < ...
    before_after.p_value(2, 2)) && ...
    all(before_after.p_value_postbin_vs_pre_fwer_target(:) >= ...
    before_after.p_value_postbin_vs_pre(:)) && ...
    all(before_after.p_value_postbin_vs_pre_fwer_group(:) >= ...
    before_after.p_value_postbin_vs_pre(:)), ...
    'One-sided post-bin max-T correction is invalid.');
[sorted_p, sorted_order] = sort(before_after.p_value(:));
expected_holm_sorted = cummax((6:-1:1).' .* sorted_p);
expected_holm = nan(size(expected_holm_sorted));
expected_holm(sorted_order) = min(1, expected_holm_sorted);
assert(max(abs(before_after.p_value_holm(:) - expected_holm)) < 1e-12, ...
    'Holm correction across the six before/after tests is wrong.');
before_after_repeat = compare_behavior_before_after_probability( ...
    wrap_recording, {'Pounce', 'PounceI'}, before_after_options);
assert(isequal(before_after.null_difference, ...
    before_after_repeat.null_difference) && ...
    isequal(before_after.p_value_postbin_vs_pre, ...
    before_after_repeat.p_value_postbin_vs_pre), ...
    'The before/after permutation is not reproducible for a fixed seed.');
self_options = before_after_options;
self_options.actor_relation = 'self';
self_options.n_permutations = 19;
self_before_after = compare_behavior_before_after_probability( ...
    wrap_recording, {'Pounce', 'PounceI'}, self_options);
assert(max(abs(self_before_after.observed_difference(:) - ...
    before_after.observed_difference(:))) < 1e-12, ...
    'Self and either disagreed for target-performer behavior.');
partner_options = self_options;
partner_options.actor_relation = 'partner';
partner_before_after = compare_behavior_before_after_probability( ...
    wrap_recording, {'Pounce', 'PounceI'}, partner_options);
assert(abs(partner_before_after.observed_difference(2, 2)) < 1e-12 && ...
    abs(partner_before_after.post_probability(2, 2)) < 1e-12, ...
    'Partner aggressive probability included the target performer.');
assert(isequal(before_after.pre_average_index, wrap_recording.pre_index) && ...
    abs(before_after.pre_average_window(1) + 0.2) < 1e-12 && ...
    before_after.pre_average_window(2) == 0, ...
    'An empty pre window did not average the whole pre-onset flank.');
narrow_options = before_after_options;
narrow_options.pre_average_window = [-0.1 0];
narrow_options.n_permutations = 19;
narrow_before_after = compare_behavior_before_after_probability( ...
    wrap_recording, {'Pounce', 'PounceI'}, narrow_options);
near_onset = wrap_recording.pre_index( ...
    abs(wrap_recording.pre_lag + 0.1) < 1e-12);
assert(isequal(narrow_before_after.pre_average_index, near_onset) && ...
    abs(narrow_before_after.pre_probability(3, 1) - ...
    before_after.probability(3, 1, near_onset)) < 1e-12, ...
    'pre_average_window did not select the requested pre-onset samples.');
invalid_pre_window = false;
try
    outside_options = narrow_options;
    outside_options.pre_average_window = [-1 0];
    compare_behavior_before_after_probability( ...
        wrap_recording, {'Pounce', 'PounceI'}, outside_options);
catch exception
    invalid_pre_window = strcmp(exception.identifier, ...
        'compare_behavior_before_after_probability:PreWindow');
end
assert(invalid_pre_window, ...
    'A before window outside the stored pre flank was accepted.');

disp('test_behavior_probability passed');
end
