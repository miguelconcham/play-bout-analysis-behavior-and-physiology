function test_behavior_probability()
%TEST_BEHAVIOR_PROBABILITY Checks using synthetic behavior annotations.

this_dir = fileparts(mfilename('fullpath'));
if ~isempty(this_dir)
    addpath(this_dir);
end

Animal = { ...
    'Session_structure'; 'RatA'; 'RatB'; 'RatA'; 'RatB'; 'RatA'; ...
    'Session_structure'; 'RatC'; 'RatA'};
Start = [0; 1; 1.99; 1.90; 3; 3.99; 20; 21; 21.90];
End = [10; 2; 2.02; 2.10; 4; 4.01; 30; 22; 22.10];
Length = End - Start;
Type = { ...
    'Partners session'; 'Pounce_A'; 'Bite'; 'Grooming'; 'Bite'; ...
    'Sniffing'; 'Partners session'; 'Bite'; 'Scratch'};
behavior = table(Animal, Start, End, Length, Type);

options = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce', 'Bite'}}, ...
    'time_window', [-0.1 0.1], ...
    'bin_size', 0.1));
recording = GENERATE_BEHAVIOR_PROBABILITY(behavior, 'RatA', options);

assert(numel(recording.sessions) == 2, ...
    'The two partner-play sessions were not retained separately.');
assert(isequal(recording.time, [-0.1 0 0.1]), ...
    'The requested offset-relative bins changed.');
assert(isequal(size(recording.sessions(1).self_behavior), [3 14 3]), ...
    'Session 1 does not have target x behavior x time dimensions.');
assert(isequal(size(recording.sessions(2).self_behavior), [1 14 3]), ...
    'Session 2 target count is wrong.');

pounce = find(strcmp(recording.behavior_types, 'Pounce'));
bite = find(strcmp(recording.behavior_types, 'Bite'));
grooming = find(strcmp(recording.behavior_types, 'Grooming'));
sniffing = find(strcmp(recording.behavior_types, 'Sniffing'));
scratching = find(strcmp(recording.behavior_types, 'Scratching'));
zero_bin = find(recording.time == 0);

first_session = recording.sessions(1);
pounce_event = find(strcmp(first_session.target_behavior, 'Pounce'));
bite_event = find(abs(first_session.target_offset - 4) < 1e-12);
assert(first_session.self_behavior(pounce_event, pounce, zero_bin), ...
    'Pounce_A was not normalized to self Pounce at its offset.');
assert(first_session.self_behavior(pounce_event, grooming, zero_bin), ...
    'Concurrent self Grooming was not represented.');
assert(first_session.partner_behavior(pounce_event, bite, zero_bin), ...
    'Concurrent partner Bite was not represented.');
assert(strcmp(first_session.target_actor{bite_event}, 'RatB'), ...
    'The partner-performed target was not retained.');
assert(first_session.self_behavior(bite_event, bite, zero_bin), ...
    'Self did not follow the target performer for a partner target.');
assert(first_session.partner_behavior(bite_event, sniffing, zero_bin), ...
    'The focal animal was not treated as partner to a partner target.');

second_session = recording.sessions(2);
assert(strcmp(second_session.target_actor{1}, 'RatC'), ...
    'The second session target actor is wrong.');
assert(second_session.partner_behavior(1, scratching, zero_bin), ...
    'Scratch was not normalized to partner Scratching.');

pounce_only = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce'}}, ...
    'time_window', [-0.1 0.1], ...
    'bin_size', 0.1));
pounce_recording = GENERATE_BEHAVIOR_PROBABILITY( ...
    behavior, 'RatA', pounce_only);
assert(size(pounce_recording.sessions(1).self_behavior, 1) == 1, ...
    'Single-target selection did not keep the Pounce event.');
assert(isequal(size(pounce_recording.sessions(2).self_behavior), [0 14 3]), ...
    'A session without a selected target did not retain an empty matrix.');

% A window from one session must not include behavior in the next session.
boundary_behavior = table( ...
    {'Session_structure'; 'RatA'; 'Session_structure'; 'RatA'}, ...
    [0; 0.8; 1; 1.0], [1; 0.9; 2; 1.2], ...
    [1; 0.1; 1; 0.2], ...
    {'Partners session'; 'Pounce_A'; 'Partners session'; 'Grooming'}, ...
    'VariableNames', {'Animal', 'Start', 'End', 'Length', 'Type'});
boundary_options = behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce'}}, ...
    'time_window', [-0.1 0.2], ...
    'bin_size', 0.1));
boundary_recording = GENERATE_BEHAVIOR_PROBABILITY( ...
    boundary_behavior, 'RatA', boundary_options);
boundary_grooming = find(strcmp( ...
    boundary_recording.behavior_types, 'Grooming'));
assert(~any(boundary_recording.sessions(1).self_behavior( ...
    1, boundary_grooming, :), 'all'), ...
    'Behavior from the next play session leaked into the first matrix.');

analysis = summarize_behavior_probability(recording);
assert(analysis.n_sessions_total == 2 && ...
    analysis.n_sessions_with_targets == 2, ...
    'Per-session probability summary lost a play session.');
assert(analysis.total_target_events == 4, ...
    'The pooled target-event count is wrong.');
expected = 1 / 4;
assert(abs(analysis.event_weighted_partner(scratching, zero_bin) - ...
    expected) < 1e-12, ...
    'Event-weighted behavior probability is wrong.');

disp('test_behavior_probability passed');
end
