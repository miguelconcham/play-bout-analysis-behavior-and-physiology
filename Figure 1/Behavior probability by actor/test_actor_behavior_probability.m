function test_actor_behavior_probability()
%TEST_ACTOR_BEHAVIOR_PROBABILITY Synthetic multi-animal pipeline checks.

this_dir = fileparts(mfilename('fullpath'));
addpath(this_dir);

Animal = { ...
    'Session_structure'; ...
    'A'; 'A'; 'B'; 'C'; ...
    'A'; 'A'; 'B'; 'C'; ...
    'B'; 'D'};
Start = [ ...
    0; ...
    4.9; 5.15; 5.18; 5.18; ...
    9.9; 10.18; 10.18; 10.18; ...
    14.9; 3];
End = [ ...
    20; ...
    5.2; 5.25; 5.25; 5.25; ...
    10.2; 10.25; 10.25; 10.25; ...
    15.2; 3.2];
Length = End - Start;
Type = { ...
    'Partners session'; ...
    'Pounce_A'; 'Grooming'; 'Bite'; 'Grooming'; ...
    'Pounce_Ai'; 'Sniffing'; 'Grooming'; 'Bite'; ...
    'Pounce_Bi'; 'Unscored_behavior'};
behavior = table(Animal, Start, End, Length, Type);

options = actor_behavior_probability_options(struct( ...
    'target_behaviors', {{'Pounce', 'PounceI'}}, ...
    'time_window', [-0.2 0.2], ...
    'bin_size', 0.1, ...
    'comparison_window', [0 0.2], ...
    'flank_seconds', 0.2, ...
    'wrapped_bins', 3));
recording = GENERATE_ACTOR_BEHAVIOR_PROBABILITY(behavior, options);

assert(numel(recording.sessions) == 1, ...
    'The Partners session was not retained.');
session = recording.sessions(1);
assert(isequal(session.participant_animals, {'A', 'B', 'C', 'D'}), ...
    ['Participants must include every real animal in the session, even ' ...
    'when an animal has no selected behavior.']);
assert(numel(session.actor_data) == 4, ...
    'One actor block per session animal was not generated.');

a = session.actor_data(strcmp({session.actor_data.actor}, 'A'));
b = session.actor_data(strcmp({session.actor_data.actor}, 'B'));
c = session.actor_data(strcmp({session.actor_data.actor}, 'C'));
d = session.actor_data(strcmp({session.actor_data.actor}, 'D'));
assert(isequal(a.other_animals, {'B', 'C', 'D'}), ...
    'A does not contain all other session animals.');
assert(isequal(a.target_behavior, {'Pounce'; 'PounceI'}), ...
    'A target events were not kept in temporal order.');
assert(isequal(b.target_behavior, {'PounceI'}), ...
    'B target behavior was not assigned to B.');
assert(isempty(c.target_behavior) && isempty(d.target_behavior), ...
    'Animals without targets must retain empty actor blocks.');

pounce = find(strcmp(recording.behavior_types, 'Pounce'));
pounce_i = find(strcmp(recording.behavior_types, 'PounceI'));
bite = find(strcmp(recording.behavior_types, 'Bite'));
grooming = find(strcmp(recording.behavior_types, 'Grooming'));
sniffing = find(strcmp(recording.behavior_types, 'Sniffing'));
zero_bin = find(recording.time == 0);
a_pounce = find(strcmp(a.target_behavior, 'Pounce'));
a_pounce_i = find(strcmp(a.target_behavior, 'PounceI'));

assert(a.self_behavior(a_pounce, pounce, zero_bin), ...
    'A target was not present in A self behavior.');
assert(a.self_behavior(a_pounce, grooming, zero_bin), ...
    'Concurrent A behavior was not assigned to self.');
assert(a.other_behavior(a_pounce, bite, zero_bin) && ...
        a.other_behavior(a_pounce, grooming, zero_bin), ...
    'Behaviors from B and C were not combined into A other behavior.');
assert(a.self_behavior(a_pounce_i, sniffing, zero_bin), ...
    'A post-target self behavior was not retained.');
assert(a.other_behavior(a_pounce_i, bite, zero_bin), ...
    'C behavior was not assigned to other for A.');
assert(b.self_behavior(1, pounce_i, zero_bin), ...
    'B target was not assigned to B self behavior.');
assert(~any(c.self_behavior, 'all') && ~any(d.other_behavior, 'all'), ...
    'Empty target blocks contain behavior samples.');

analysis = summarize_actor_behavior_probability(recording);
assert(analysis.n_actor_session_strata == 4, ...
    'Actor-session stratum count is wrong.');
assert(isequal(analysis.n_events, [1 2]), ...
    'Target-specific event counts are wrong.');
assert(isequal(analysis.n_strata_with_target, [1 2]), ...
    'Target-specific actor-stratum counts are wrong.');

pair_settings = struct('relation', 'other', ...
    'test_window', [0 0.2], 'n_permutations', 19, 'random_seed', 3);
pair = compare_actor_behavior_pair_probability( ...
    recording, {'Pounce', 'PounceI'}, pair_settings);
assert(pair.n_eligible_strata == 1, ...
    'Pair comparison was not restricted to A, who performed both targets.');
assert(isequal(pair.n_events_test, [1 1]), ...
    'Pair comparison event counts are wrong.');
assert(strcmp(pair.relation, 'other') && ...
        isequal(size(pair.probability), [3 2 5]), ...
    'Pair comparison did not retain the other relation or expected shape.');

baseline_settings = struct('relation', 'self', ...
    'pre_average_window', [], 'n_permutations', 19, 'random_seed', 4);
baseline = compare_actor_behavior_baseline_probability( ...
    recording, {'Pounce', 'PounceI'}, baseline_settings);
assert(isequal(baseline.n_events_test, [1 2]), ...
    'Baseline comparison event counts are wrong.');
assert(isequal(size(baseline.observed_difference_by_bin), [3 2 2]), ...
    'Baseline bin-wise results have the wrong dimensions.');
assert(all(baseline.p_value(:) >= 0 & baseline.p_value(:) <= 1), ...
    'Baseline permutation p-values are invalid.');

disp('test_actor_behavior_probability passed');
end
