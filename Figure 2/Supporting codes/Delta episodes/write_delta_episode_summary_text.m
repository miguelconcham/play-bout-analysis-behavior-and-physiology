function write_delta_episode_summary_text(recordings, summary_table, output_file)
%WRITE_DELTA_EPISODE_SUMMARY_TEXT  Plain-text results for later review.
%
% The file states the question, the detection settings, one line per
% mid-LPAG channel, and the pooled cycle-period distribution. It is meant
% to be readable without the MAT file.

file_id = fopen(output_file, 'w');
if file_id < 0
    error('write_delta_episode_summary_text:file', ...
        'Could not write %s.', output_file);
end
cleaner = onCleanup(@() fclose(file_id)); %#ok<NASGU>

parameters = recordings(1).parameters;
fprintf(file_id, 'Delta oscillatory episode summary\n');
fprintf(file_id, '=================================\n\n');
fprintf(file_id, ['Question: do sustained 1-5 Hz episodes occur in the ' ...
    'continuous mid-LPAG LFP, and what periods and waveform shapes do ' ...
    'their cycles have?\n\n']);
fprintf(file_id, 'This is not a play-versus-non-play comparison.\n');
fprintf(file_id, ['A 1-5 Hz filter can ring around a transient, so an ' ...
    'episode is a candidate until the minimally processed trace agrees.\n\n']);

fprintf(file_id, 'Detection settings\n');
fprintf(file_id, '------------------\n');
fprintf(file_id, 'Band: %.3g-%.3g Hz\n', parameters.delta_freq(1), ...
    parameters.delta_freq(2));
fprintf(file_id, 'Interval mode: %s\n', parameters.interval_mode);
fprintf(file_id, 'Amplitude threshold: %s = %.4g\n', ...
    parameters.amplitude_threshold_mode, parameters.amplitude_threshold);
fprintf(file_id, 'Minimum peak-to-peak cycles: %.4g\n', parameters.min_cycles);
fprintf(file_id, ['Cycle preset: %s (amplitude consistency >= %.3g, ' ...
    'period consistency >= %.3g, monotonicity >= %.3g, amplitude ' ...
    'percentile %.4g, minimum consecutive cycles %.4g)\n\n'], ...
    parameters.cycle_threshold_preset, parameters.amp_consistency_threshold, ...
    parameters.period_consistency_threshold, parameters.monotonicity_threshold, ...
    parameters.cycle_amplitude_percentile, parameters.min_consecutive_cycles);

animals = unique(summary_table.animal_name, 'stable');
fprintf(file_id, 'Recordings: %d mid-LPAG channels from %d animals.\n\n', ...
    height(summary_table), numel(animals));

fprintf(file_id, 'Per channel\n');
fprintf(file_id, '-----------\n');
fprintf(file_id, ['animal | probe | channel | analyzed_s | episodes | ' ...
    'sustained_episodes | episode_time_fraction | median_duration_s | ' ...
    'median_trough_cycles | median_trough_period_ms | trough_period_CV | ' ...
    'median_rise_decay_symmetry | median_peak_trough_symmetry | ' ...
    'fraction_of_peak_cycles_in_1_to_5_Hz\n']);
for row_n = 1:height(summary_table)
    fprintf(file_id, ['%s | %g | %g | %.3g | %g | %g | %.4g | %.4g | ' ...
        '%.4g | %.4g | %.4g | %.4g | %.4g | %.4g\n'], ...
        summary_table.animal_name{row_n}, summary_table.probe_number(row_n), ...
        summary_table.lpag_channel(row_n), summary_table.analyzed_seconds(row_n), ...
        summary_table.n_episodes(row_n), ...
        summary_table.n_episodes_with_sustained_sequence(row_n), ...
        summary_table.episode_time_fraction(row_n), ...
        summary_table.median_duration_s(row_n), ...
        summary_table.median_n_trough_cycles(row_n), ...
        1000 * summary_table.median_trough_period_s(row_n), ...
        summary_table.median_trough_period_cv(row_n), ...
        summary_table.median_rdsym(row_n), summary_table.median_ptsym(row_n), ...
        summary_table.pooled_fraction_cycles_in_delta_band(row_n));
end

periods_s = all_periods(recordings);
fprintf(file_id, '\nPooled trough-to-trough cycles: %d\n', numel(periods_s));
if isempty(periods_s)
    fprintf(file_id, 'No trough cycles were saved.\n');
else
    periods_ms = 1000 * periods_s(:);
    band_ms = [1000 / parameters.delta_freq(2), 1000 / parameters.delta_freq(1)];
    in_band = periods_ms >= band_ms(1) & periods_ms <= band_ms(2);
    percentiles = percentile_row(periods_ms, [5 25 50 75 95]);
    fprintf(file_id, 'Period percentiles (ms), 5/25/50/75/95: %.1f %.1f %.1f %.1f %.1f\n', ...
        percentiles);
    fprintf(file_id, ['Cycles inside %.0f-%.0f ms (%.3g-%.3g Hz): ' ...
        '%d of %d (%.1f%%)\n'], band_ms(1), band_ms(2), ...
        parameters.delta_freq(2), parameters.delta_freq(1), ...
        nnz(in_band), numel(periods_ms), 100 * mean(in_band));
    edges = 50:50:1000;
    counts = histcounts_local(periods_ms, edges);
    fprintf(file_id, '\nPeriod histogram, 50 ms bins from 50 to 1000 ms\n');
    fprintf(file_id, 'bin_start_ms | bin_end_ms | cycles\n');
    for bin_n = 1:numel(counts)
        fprintf(file_id, '%g | %g | %g\n', edges(bin_n), edges(bin_n + 1), ...
            counts(bin_n));
    end
end

fprintf(file_id, ['\nAcross-channel medians: episode time fraction %.3g, ' ...
    'rise-decay symmetry %.3g, peak-trough symmetry %.3g, monotonicity %.3g.\n'], ...
    median(summary_table.episode_time_fraction, 'omitnan'), ...
    median(summary_table.median_rdsym, 'omitnan'), ...
    median(summary_table.median_ptsym, 'omitnan'), ...
    median(summary_table.median_monotonicity, 'omitnan'));
fprintf(file_id, ['Symmetry near 0.5 is a balanced flank. A rise-decay value ' ...
    'well above or below 0.5 means an asymmetric waveform.\n']);
fprintf(file_id, ['Channels from the same animal are repeated measures. ' ...
    'This text does not contain an animal-level significance test.\n']);
end

function values = percentile_row(x, percentiles)
values = nan(size(percentiles));
for percentile_n = 1:numel(percentiles)
    values(percentile_n) = linear_percentile(x, percentiles(percentile_n));
end
end

function periods_s = all_periods(recordings)
periods_s = zeros(0, 1);
for recording_n = 1:numel(recordings)
    recording = recordings(recording_n);
    if isfield(recording, 'cycles') && ~isempty(recording.cycles)
        periods_s = [periods_s; [recording.cycles.period_s]']; %#ok<AGROW>
    end
end
end

function counts = histcounts_local(values, edges)
counts = zeros(1, numel(edges) - 1);
for bin_n = 1:numel(counts)
    if bin_n < numel(counts)
        counts(bin_n) = nnz(values >= edges(bin_n) & values < edges(bin_n + 1));
    else
        counts(bin_n) = nnz(values >= edges(bin_n) & values <= edges(bin_n + 1));
    end
end
end
