function grouped = theta_envelope_group_behaviors(recordings, min_events)
%THETA_ENVELOPE_GROUP_BEHAVIORS  Animal test for each behavior, actor, and measure.
%
% One entry per behavior of the implanted animal and of the partner, and for
% the Hilbert envelope and the spectrogram power. Animals with fewer than
% min_events valid windows of that behavior stay in the entry and are left
% out of its p-values.

if isempty(recordings) || ~isfield(recordings, 'behavior') || isempty(recordings(1).behavior)
    grouped = repmat(empty_grouped(), 0, 1);
    return
end
if nargin < 2 || isempty(min_events)
    min_events = 15;
end
template = recordings(1).behavior;
actors = {'self', 'partner'};
measures = {'envelope', 'power'};
grouped = repmat(empty_grouped(), numel(template) * numel(actors) * numel(measures), 1);
entry_n = 0;
for behavior_n = 1:numel(template)
    for actor_n = 1:numel(actors)
        for measure_n = 1:numel(measures)
            subset = recordings;
            for recording_n = 1:numel(recordings)
                block = recordings(recording_n).behavior(behavior_n).(actors{actor_n}).(measures{measure_n});
                onset = struct();
                onset.epoch_time = block.epoch_time;
                onset.mean_epoch = block.mean_epoch;
                if isempty(block.mean_epoch)
                    onset.epochs = zeros(0, numel(block.epoch_time));
                    onset.mean_epoch = nan(1, numel(block.epoch_time));
                else
                    onset.epochs = block.mean_epoch(:).';
                end
                onset.clean_pre = true(size(onset.epochs, 1), 1);
                onset.pre = block.pre;
                onset.loo_r = block.pre(1).loo_r;
                subset(recording_n).onset = onset;
            end
            summary = theta_envelope_group_onsets(subset, min_events);
            entry_n = entry_n + 1;
            summary.behavior = template(behavior_n).name;
            summary.actor = actors{actor_n};
            summary.measure = measures{measure_n};
            summary.is_play = template(behavior_n).is_play;
            grouped(entry_n) = summary;
        end
    end
end
grouped = grouped(1:entry_n);
end

function grouped = empty_grouped()
grouped = struct( ...
    'animals', {{}}, ...
    'frequencies', [], ...
    'confirmatory_mask', [], ...
    'epoch_time', [], ...
    'n_trials', [], ...
    'included', [], ...
    'locked_amplitude', [], ...
    'ppc', [], ...
    'loo_mean_r', [], ...
    'phase_fraction', [], ...
    'mean_epoch', [], ...
    'clean_mean_epoch', [], ...
    'grand_mean_epoch', [], ...
    'grand_clean_epoch', [], ...
    'confirmatory_locked', [], ...
    'confirmatory_ppc', [], ...
    'animal_locked_p', [], ...
    'animal_ppc_p', [], ...
    'animal_loo_p', [], ...
    'animal_phase_p', [], ...
    'locked_p', NaN, ...
    'ppc_p', NaN, ...
    'loo_p', NaN, ...
    'phase_fraction_p', NaN, ...
    'behavior', '', ...
    'actor', '', ...
    'measure', '', ...
    'is_play', false);
end
