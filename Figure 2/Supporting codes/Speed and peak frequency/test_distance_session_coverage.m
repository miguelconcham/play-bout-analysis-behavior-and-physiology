function test_distance_session_coverage()
%TEST_DISTANCE_SESSION_COVERAGE  Counts sessions at each inter-animal distance.
%
% The cuts match the high-speed section of Analyze_speed_freq_relation.
% Run this file by name after add_repo_paths. It does not load experiment files.

this_dir = fileparts(mfilename('fullpath'));
if ~isempty(this_dir)
    addpath(this_dir);
end

options = distance_coverage_options();
assert(options.high_z == 1, 'The distance cut is not one session z.');
assert(options.ceiling_bin_width == 0.5, 'The ceiling bin is not 0.5 z.');
assert(options.min_nonplay_s == 2, 'The non-play tail minimum is not 2 s.');
assert(options.min_play_s == 1, 'The play tail minimum is not 1 s.');
assert(options.min_ceiling_nonplay_s == 1, 'The ceiling non-play minimum is not 1 s.');
assert(options.min_ceiling_play_s == 0.5, 'The ceiling play minimum is not 0.5 s.');
assert(options.curve_bin_width == 0.25, 'The count bin is not 0.25 z.');
assert(options.min_bin_nonplay_s == 0.5, 'The bin non-play minimum is not 0.5 s.');
assert(options.min_bin_play_s == 0.5, 'The bin play minimum is not 0.5 s.');
assert(options.curve_z_limit == 6, 'The count curve does not stop at z = 6.');

changed = distance_coverage_options(struct('curve_z_limit', 4));
assert(changed.curve_z_limit == 4, 'A curve limit override was ignored.');
assert(changed.high_z == 1, 'An override cleared the distance cut.');
assert_error(@() distance_coverage_options(struct('not_an_option', 1)), ...
    'distance_coverage_options:UnknownOption');

hop = 0.125;
play_power = 2;
nonplay_power = 1;
distance_a = [ ...
    repmat(1.25, 8, 1); ...
    repmat(1.25, 8, 1); ...
    repmat(1.5, 8, 1); ...
    repmat(-1.25, 8, 1); ...
    repmat(-1.25, 8, 1)];
play_a = [true(8, 1); false(8, 1); false(8, 1); true(8, 1); false(8, 1)];
power_a = [ ...
    repmat(play_power, 8, 1); ...
    repmat(nonplay_power, 8, 1); ...
    repmat(nonplay_power, 8, 1); ...
    repmat(play_power, 8, 1); ...
    repmat(nonplay_power, 8, 1)];
sessions = [ ...
    make_session(distance_a, power_a, play_a, hop, 'A', 1), ...
    make_session(repmat(1.25, 4, 1), ones(4, 1), false(4, 1), hop, 'B', 2), ...
    make_session(repmat(1.25, 4, 1), repmat(2, 4, 1), true(4, 1), hop, 'A', 3), ...
    make_session([], [], [], hop, 'E', 4)];
report = distance_coverage_report(sessions, options);

assert(report.n_sessions == 4, 'An empty session was dropped.');
assert(abs(report.nonplay_far_s(1) - 2) < 1e-12, ...
    'Far non-play is not 2 s.');
assert(abs(report.play_far_s(1) - 1) < 1e-12, 'Far play is not 1 s.');
assert(report.enough_far(1), '2 s non-play and 1 s play did not pass.');
assert(~report.enough_far(2) && ~report.enough_far(3) && ~report.enough_far(4), ...
    'A session without both tails was marked enough.');
assert(abs(report.nonplay_close_s(1) - 1) < 1e-12, 'Close non-play is not 1 s.');
assert(abs(report.play_close_s(1) - 1) < 1e-12, 'Close play is not 1 s.');
assert(~report.enough_close(1), '1 s of close non-play passed the 2 s minimum.');
assert(abs(report.diff_far(1) - 1) < 1e-12, ...
    'The far difference is not play minus non-play.');
assert(abs(report.diff_close(1) - 1) < 1e-12, ...
    'The close difference is not play minus non-play.');
assert(abs(report.diff_far_z(1) - 1 / std(power_a)) < 1e-12, ...
    'The far difference was not scaled by the session standard deviation.');
assert(abs(report.diff_close_z(1) - report.diff_far_z(1)) < 1e-12, ...
    'Close and far z differences diverged for the same power values.');
assert(isnan(report.diff_far(2)) && isnan(report.diff_far(3)), ...
    'A tail with one class still produced a difference.');
assert(abs(report.max_nonplay(1) - 1.5) < 1e-12, 'Max non-play distance is wrong.');
assert(abs(report.max_play(1) - 1.25) < 1e-12, 'Max play distance is wrong.');
assert(abs(report.min_nonplay(1) + 1.25) < 1e-12, 'Min non-play distance is wrong.');
assert(abs(report.min_play(1) + 1.25) < 1e-12, 'Min play distance is wrong.');
assert(isnan(report.max_play(2)) && abs(report.max_nonplay(2) - 1.25) < 1e-12, ...
    'A non-play-only session invented a play distance.');
assert(report.nonplay_far_s(4) == 0 && isnan(report.max_nonplay(4)), ...
    'An empty session contributed duration or a distance.');

assert(abs(report.far_bin_lo(1) - 1) < 1e-12 ...
    && abs(report.far_bin_hi(1) - 1.5) < 1e-12, ...
    'The farthest supported bin is not [1, 1.5].');
assert(abs(report.far_bin_play_s(1) - 1) < 1e-12 ...
    && abs(report.far_bin_nonplay_s(1) - 2) < 1e-12, ...
    'The farthest bin durations are wrong.');
assert(abs(report.diff_far_bin(1) - 1) < 1e-12, ...
    'The farthest bin difference is not play minus non-play.');
assert(abs(report.close_bin_lo(1) + 1.5) < 1e-12 ...
    && abs(report.close_bin_hi(1) + 1) < 1e-12, ...
    'The closest supported bin is not [-1.5, -1].');
assert(isnan(report.far_bin_lo(2)), ...
    'Non-play alone produced a supported bin.');

assert(abs(report.curve_edges(1) + 1.25) < 1e-12, ...
    'The count curve does not start at the closest sample.');
assert(abs(report.curve_edges(end) - 2) < 1e-12, ...
    'The count curve does not reach z = 2.');
assert(max(abs(diff(report.curve_edges) - options.curve_bin_width)) < 1e-12, ...
    'Count bins are not 0.25 z wide.');

shared = bin_at(report.curve_x, 1.375);
above = bin_at(report.curve_x, 1.625);
close_bin = bin_at(report.curve_x, -1.125);
assert(abs(report.play_power(1, shared) - 2) < 1e-12, ...
    'Play delta power at the shared distance is not 2.');
assert(abs(report.nonplay_power(1, shared) - 1) < 1e-12, ...
    'Non-play delta power at the shared distance is not 1.');
assert(report.play_power(1, shared) > report.nonplay_power(1, shared), ...
    'Play power is not higher at the same distance.');
assert(abs(report.diff_all(1, shared) - ...
    (report.play_power(1, shared) - report.nonplay_power(1, shared))) < 1e-12, ...
    'The matched difference is not play minus non-play.');
assert(isnan(report.play_power(2, shared)) && isnan(report.nonplay_power(3, shared)), ...
    'A session missing one class still entered the matched comparison.');
assert(report.n_both(shared) == 1, 'Both-session count at z = 1.25 is wrong.');
assert(report.n_play(shared) == 2, 'Play-session count at z = 1.25 is wrong.');
assert(report.n_nonplay(shared) == 2, 'Non-play-session count at z = 1.25 is wrong.');
assert(report.n_both(above) == 0 && report.n_play(above) == 0 ...
    && report.n_nonplay(above) == 1, ...
    'The non-play-only bin above 1.5 was not counted alone.');
assert(report.n_both(close_bin) == 1 && report.n_play(close_bin) == 1 ...
    && report.n_nonplay(close_bin) == 1, ...
    'The close bin did not count its one session.');
assert(abs(report.diff_all(1, shared) - 1) < 1e-12, ...
    'The comparable-session difference at z = 1.25 is wrong.');
assert(all(isnan(report.diff_all(2, :))), ...
    'A non-play-only session entered the play-minus-non-play curve.');
assert(report.n_both_far(shared) == 1 && report.n_play_far(shared) == 1 ...
    && report.n_nonplay_far(shared) == 1, ...
    'The far-qualified session was left out of its own bin.');
assert(all(report.n_both_close == 0), ...
    'A session under the close minimum was treated as qualified.');

print_distance_coverage(report);

short = distance_coverage_report(make_session( ...
    repmat(1.25, 3, 1), ones(3, 1), false(3, 1), hop, 'F', 1));
assert(short.n_nonplay(bin_at(short.curve_x, 1.375)) == 0, ...
    '0.375 s of non-play met the 0.5 s bin minimum.');
exact = distance_coverage_report(make_session( ...
    repmat(1.25, 4, 1), ones(4, 1), false(4, 1), hop, 'F', 1));
assert(exact.n_nonplay(bin_at(exact.curve_x, 1.375)) == 1, ...
    '0.5 s of non-play missed the bin minimum.');

one_class = distance_coverage_report(make_session( ...
    repmat(1.25, 28, 1), [repmat(2, 4, 1); ones(24, 1)], ...
    [true(4, 1); false(24, 1)], hop, 'G', 1));
assert(~one_class.enough_far, '0.5 s of play passed the 1 s play minimum.');
assert(abs(one_class.play_far_s - 0.5) < 1e-12, 'Play tail duration is wrong.');
assert(abs(one_class.nonplay_far_s - 3) < 1e-12, 'Non-play tail duration is wrong.');
assert(abs(one_class.diff_far - 1) < 1e-12, ...
    'Play and non-play in the tail did not produce a difference.');

on_cut = distance_coverage_report(make_session( ...
    ones(8, 1), [repmat(2, 4, 1); ones(4, 1)], ...
    [true(4, 1); false(4, 1)], hop, 'H', 1));
assert(abs(on_cut.play_far_s - 0.5) < 1e-12 ...
    && abs(on_cut.nonplay_far_s - 0.5) < 1e-12, ...
    'z = 1 was left out of the far tail.');
assert(on_cut.n_both(bin_at(on_cut.curve_x, 1.125)) == 1, ...
    'A sample on an interior edge was not counted in the higher bin.');
assert(on_cut.n_both(bin_at(on_cut.curve_x, 0.875)) == 0, ...
    'A sample on an interior edge was also counted in the lower bin.');

below_cut = distance_coverage_report(make_session( ...
    repmat(0.75, 16, 1), ones(16, 1), true(16, 1), hop, 'L', 1));
assert(below_cut.play_far_s == 0 && below_cut.nonplay_far_s == 0, ...
    'z = 0.75 entered the far tail.');
assert(below_cut.play_close_s == 0 && below_cut.nonplay_close_s == 0, ...
    'z = 0.75 entered the close tail.');

at_close = distance_coverage_report(make_session( ...
    repmat(-1, 16, 1), ones(16, 1), false(16, 1), hop, 'C', 1));
assert(abs(at_close.nonplay_close_s - 2) < 1e-12, ...
    'z = -1 was left out of the close tail.');
near_close = distance_coverage_report(make_session( ...
    repmat(-0.75, 16, 1), ones(16, 1), false(16, 1), hop, 'C', 1));
assert(near_close.nonplay_close_s == 0, 'z = -0.75 entered the close tail.');

at_right_edge = distance_coverage_report(make_session( ...
    repmat(2, 8, 1), [repmat(3, 4, 1); ones(4, 1)], ...
    [true(4, 1); false(4, 1)], hop, 'R', 1));
assert(at_right_edge.n_both(bin_at(at_right_edge.curve_x, 1.875)) == 1, ...
    'The last distance bin excluded its right edge.');
assert(at_right_edge.n_both(bin_at(at_right_edge.curve_x, 1.625)) == 0, ...
    'A right-edge sample was counted in the previous bin.');

outside = distance_coverage_report(make_session( ...
    [6.5; 6.5; -6.5; -6.5], [2; 1; 2; 1], [true; false; true; false], 1, 'O', 1));
assert(abs(outside.curve_edges(1) + 6) < 1e-12 ...
    && abs(outside.curve_edges(end) - 6) < 1e-12, ...
    'The count curve did not clip at z = 6.');
assert(all(outside.n_both == 0) && all(outside.n_play == 0) ...
    && all(outside.n_nonplay == 0), ...
    'A sample outside z = 6 was counted in a bin.');
assert(abs(outside.play_far_s - 1) < 1e-12 ...
    && abs(outside.nonplay_far_s - 1) < 1e-12, ...
    'The far tail dropped samples beyond the count curve.');
assert(abs(outside.play_close_s - 1) < 1e-12 ...
    && abs(outside.nonplay_close_s - 1) < 1e-12, ...
    'The close tail dropped samples beyond the count curve.');

skipped = distance_coverage_report(make_session( ...
    [-1.25; -1.25; 0.25; 0.25], [4; 4; 4; 1], [true; true; true; false], 1, 'S', 1));
assert(abs(skipped.close_bin_lo - 0) < 1e-12 ...
    && abs(skipped.close_bin_hi - 0.5) < 1e-12, ...
    'The closest bin kept a distance that has play and no non-play.');
assert(abs(skipped.diff_close_bin - 3) < 1e-12, ...
    'The closest supported difference is wrong.');

skipped_far = distance_coverage_report(make_session( ...
    [1.5; 1.5; 0.25; 0.25], [4; 4; 4; 1], [true; true; true; false], 1, 'S', 1));
assert(abs(skipped_far.far_bin_lo - 0) < 1e-12 ...
    && abs(skipped_far.far_bin_hi - 0.5) < 1e-12, ...
    'The farthest bin kept a distance that has play and no non-play.');

cleaned = distance_coverage_report(make_session( ...
    [NaN; 1.25; 5], [1; nonplay_power; NaN], [true; false; true], hop, 'N', 1));
assert(abs(cleaned.nonplay_far_s - hop) < 1e-12 && cleaned.play_far_s == 0, ...
    'Non-finite samples were kept.');
assert(abs(cleaned.max_nonplay - 1.25) < 1e-12 && isnan(cleaned.max_play), ...
    'A non-finite distance of 5 set the session maximum.');

numeric_mask = make_session([1; 1], [2; 1], [true; false], hop, 'N', 1);
numeric_mask.is_play = [1; 0];
numeric_report = distance_coverage_report(numeric_mask);
assert(abs(numeric_report.play_far_s - hop) < 1e-12 ...
    && abs(numeric_report.nonplay_far_s - hop) < 1e-12, ...
    'A numeric play mask was not read as play and non-play.');

empty_report = distance_coverage_report(make_session([], [], [], hop, 'E', 1));
empty_report = distance_coverage_report(empty_report_sessions(empty_report));
assert(empty_report.n_sessions == 0, 'An empty list still reported sessions.');
assert(all(empty_report.n_both == 0), 'An empty list counted a session.');
assert(abs(empty_report.curve_edges(1) + 1) < 1e-12 ...
    && abs(empty_report.curve_edges(end) - 2) < 1e-12, ...
    'An empty list did not use the default distance axis.');

bad_hop = make_session(1, 1, true, hop, 'Z', 1);
bad_hop.hop_s = 0;
assert_error(@() distance_coverage_report(bad_hop), 'distance_coverage_report:Hop');
bad_length = make_session([1; 1], [1; 1], [true; false], hop, 'Z', 1);
bad_length.power = 1;
assert_error(@() distance_coverage_report(bad_length), ...
    'distance_coverage_report:LengthMismatch');
assert_error(@() distance_coverage_report(bad_length, ...
    distance_coverage_options(struct('high_z', 0))), ...
    'distance_coverage_report:Options');

entry = model_entry([1.25; 0], [1; 2], {'TRUE'; '0'}, [9; 9]);
entry.wind_length = 0.25;
entry.wind_overlap = 0.249;
other = model_entry([8; 8], [3; 4], {'true'; 'false'}, [0; 0]);
other.wind_length = 0.25;
other.wind_overlap = 0.249;
animal_names = {'Rat', 2, 1; 'Rat', 3, 2};
extracted = distance_coverage_sessions([entry other], animal_names);
assert(numel(extracted) == 1, 'Electrode 2 was kept.');
assert(strcmp(extracted.animal, 'Rat'), 'The animal name was not kept.');
assert(extracted.partner == 2, 'The partner number was not kept.');
assert(isequal(extracted.distance_z, [1.25; 0]), 'Distance was replaced by Speed.');
assert(isequal(extracted.is_play, [true; false]), ...
    'TRUE and 0 were not read as play and non-play.');
assert(abs(extracted.hop_s - 0.0012) < 1e-12, ...
    'A 0.25 s window with 0.249 s overlap is not a 0.0012 s hop.');
assert(abs(extracted.wind_s - 0.25) < 1e-12, 'The spectrogram window was not kept.');

numeric_entry = model_entry([1; 0], [1; 2], [1; 0], []);
logical_entry = model_entry([1; 0], [1; 2], [true; false], []);
numeric_sessions = distance_coverage_sessions(numeric_entry, {'Rat', 1, 1});
logical_sessions = distance_coverage_sessions(logical_entry, {'Rat', 1, 1});
assert(isequal(numeric_sessions.is_play, logical_sessions.is_play), ...
    'Numeric and logical play masks disagree.');
assert(abs(numeric_sessions.hop_s - 0.0012) < 1e-12, ...
    'A missing window did not fall back to a 0.0012 s hop.');

assert_error(@() distance_coverage_sessions(entry, {'Rat', 2, 1; 'Rat', 3, 1}), ...
    'distance_coverage_sessions:NameMismatch');
assert_error(@() distance_coverage_sessions(entry, {'Rat', 2, 2}), ...
    'distance_coverage_sessions:NoElectrode');
missing_distance = entry;
missing_distance.model_data = rmfield(entry.model_data, 'Distance');
assert_error(@() distance_coverage_sessions(missing_distance, {'Rat', 2, 1}), ...
    'distance_coverage_sessions:NoDistance');
missing_power = entry;
missing_power.model_data = rmfield(entry.model_data, 'Power');
assert_error(@() distance_coverage_sessions(missing_power, {'Rat', 2, 1}), ...
    'distance_coverage_sessions:NoPower');
bad_model = entry;
bad_model.model_data.Power = 1;
assert_error(@() distance_coverage_sessions(bad_model, {'Rat', 2, 1}), ...
    'distance_coverage_sessions:LengthMismatch');

if exist('pkg', 'file') == 2
    try
        pkg('load', 'statistics');
    catch
    end
end
if exist('ttest', 'file') == 2
    overlap = [true(8, 1); false(16, 1)];
    far_distance = repmat(1.25, 24, 1);
    far_power = [repmat(2, 8, 1); ones(16, 1)];
    paired = distance_coverage_report([ ...
        make_session(far_distance, far_power, overlap, hop, 'A', 1), ...
        make_session(far_distance, far_power * 0.5, overlap, hop, 'A', 2)]);
    assert(all(paired.enough_far), 'Two far-overlap sessions were not both qualified.');
    print_distance_coverage(paired);
end

assert(strcmp(analysis_figure_basename('High-speed coverage: Speed', 3), ...
    'High-speed coverage - Speed'), ...
    'A colon in a figure name was not made safe for a file name.');
assert(strcmp(analysis_figure_basename('', 4), 'figure 4'), ...
    'An unnamed figure did not use its number.');
assert(strcmp(analysis_figure_basename('Matched distance delta power', 1), ...
    'Matched distance delta power'), ...
    'A plain figure name was changed.');

disp('test_distance_session_coverage passed');
end

function session = make_session(distance_z, power, is_play, hop_s, animal, partner)
session.animal = animal;
session.partner = partner;
session.distance_z = distance_z(:);
session.power = power(:);
session.is_play = logical(is_play(:));
session.hop_s = hop_s;
session.wind_s = 0.25;
end

function entry = model_entry(distance_z, power, play_col, speed)
entry.model_data.Distance = distance_z(:);
entry.model_data.Power = power(:);
entry.model_data.Play = play_col(:);
entry.model_data.Speed = speed(:);
entry.freq_range = [1 5];
end

function index = bin_at(centers, target)
[err, index] = min(abs(centers - target));
assert(err < 1e-9, 'No count bin is centered on the expected distance.');
end

function sessions = empty_report_sessions(~)
template = make_session([], [], [], 0.125, 'E', 1);
sessions = template([]);
end

function assert_error(fn, identifier)
threw = false;
try
    fn();
catch ME
    threw = true;
    assert(strcmp(ME.identifier, identifier), ME.message);
end
assert(threw, ['Expected error ' identifier]);
end
