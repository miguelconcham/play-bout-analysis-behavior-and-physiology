function print_and_plot_distance_cm(psth_structure, animal_names, report)
%PRINT_AND_PLOT_DISTANCE_CM  Same extreme-distance points, in centimetres.
%
% The z-score figures stay. This adds the closest and farthest supported
% bins with the x-axis in centimetres, using 0.1334 cm per image pixel.

electrode_id = cellfun(@double, animal_names(:, 3));
session_rows = find(electrode_id == 1);
if numel(session_rows) ~= report.n_sessions
    error('print_and_plot_distance_cm:Size', ...
        'Electrode-1 rows (%d) do not match the distance report (%d).', ...
        numel(session_rows), report.n_sessions);
end

[close_cm, found] = session_physical_edges(psth_structure, session_rows, ...
    'Distance', 'DistanceCm', report.close_bin_lo);
if ~found
    fprintf(['\nDistance in cm is not in this mat. Tracking pixels convert as\n' ...
        'cm = pixels * %.4f. Re-run GENERATE_SPEED_FREQ_RELATION so model_data\n' ...
        'includes DistanceCm. The z-score distance plots above stay as they are.\n'], ...
        pixel_to_cm());
    return
end
[far_cm, ~] = session_physical_edges(psth_structure, session_rows, ...
    'Distance', 'DistanceCm', report.far_bin_lo);
[max_play_cm, ~] = session_physical_edges(psth_structure, session_rows, ...
    'Distance', 'DistanceCm', report.max_play);
[max_nonplay_cm, ~] = session_physical_edges(psth_structure, session_rows, ...
    'Distance', 'DistanceCm', report.max_nonplay);
[min_play_cm, ~] = session_physical_edges(psth_structure, session_rows, ...
    'Distance', 'DistanceCm', report.min_play);
[min_nonplay_cm, ~] = session_physical_edges(psth_structure, session_rows, ...
    'Distance', 'DistanceCm', report.min_nonplay);

fprintf(['\nExtreme distances in centimetres (%.4f cm per pixel).\n' ...
    'Each session uses its own mean and SD, so the same z is not the same cm.\n'], ...
    pixel_to_cm());
for s = 1:report.n_sessions
    fprintf(['%s P%d: closest bin start %s, farthest bin start %s, ' ...
        'min play %s, min non-play %s, max play %s, max non-play %s\n'], ...
        report.animals{s}, report.partners(s), ...
        cm_text(close_cm(s)), cm_text(far_cm(s)), ...
        cm_text(min_play_cm(s)), cm_text(min_nonplay_cm(s)), ...
        cm_text(max_play_cm(s)), cm_text(max_nonplay_cm(s)));
end

y_label = 'Play - non-play (log10 delta amplitude)';
close_at_cut = isfinite(report.close_bin_hi) & report.close_bin_hi <= -report.options.high_z;
far_at_cut = isfinite(report.far_bin_lo) & report.far_bin_lo >= report.options.high_z;
figure('Name', 'Extreme distance in cm')
subplot(1, 2, 1)
plot_physical_scatter(close_cm, report.diff_close_bin, close_at_cut, ...
    'Start of closest supported distance bin (cm)', y_label, ...
    'Each session at its closest supported distance', ...
    'Bin extends past the close cut', 'Bin stays at the close cut')
subplot(1, 2, 2)
plot_physical_scatter(far_cm, report.diff_far_bin, far_at_cut, ...
    'Start of farthest supported distance bin (cm)', y_label, ...
    'Each session at its farthest supported distance', ...
    'Bin starts below the far cut', 'Bin starts at the far cut')
end

function text = cm_text(value)
if ~isfinite(value)
    text = 'n/a';
    return
end
text = sprintf('%.1f cm', value);
end
