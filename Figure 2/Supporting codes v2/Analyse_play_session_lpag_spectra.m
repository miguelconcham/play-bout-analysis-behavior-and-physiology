    1 - ci_alpha / 2, fourier_theta_removed_n(valid_fourier_ci) - 1);
fourier_theta_removed_ci_half_width = ...
    fourier_theta_removed_t .* fourier_theta_removed_sem;
fourier_theta_removed_ci = [ ...
    fourier_theta_removed_mean - fourier_theta_removed_ci_half_width; ...
    fourier_theta_removed_mean + fourier_theta_removed_ci_half_width];

