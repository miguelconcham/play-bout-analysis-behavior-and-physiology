    isfinite(group_fourier_aperiodic_theta_subtracted), 1);
fourier_theta_removed_sem = std( ...
    group_fourier_aperiodic_theta_subtracted, 0, 1, 'omitnan') ./ ...
    sqrt(fourier_theta_removed_n);
