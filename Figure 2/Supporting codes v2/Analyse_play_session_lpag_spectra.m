%% Analyse_play_session_lpag_spectra
% Summarize session-wise Welch and direct-Fourier LPAG spectra and their
% periodic/aperiodic parameterizations.
%
% Two complementary periodic estimates are retained:
%   1. gaussian_periodic_fit: sum of fitted FOOOF Gaussian peaks
%   2. raw_aperiodic_subtracted: log10(PSD) - fitted aperiodic component
% The second quantity is an aperiodic-adjusted raw periodic residual.

saving_folder = '\\experimentfs.bccn-berlin.pri\experiment\PlayNeuralData\NPX-OPTO PLAY NMM\PlayBout Analysis\play bout analysis behavior and physiology\Data\Analysis results\psth power by frequency and behavior';
input_file = fullfile(saving_folder, ...
    'play_session_lpag_periodic_aperiodic_spectra.mat');

disp(['Loading ', input_file])
load(input_file, 'play_session_lpag_spectra', 'animal_names');
if isempty(play_session_lpag_spectra)
    error('The saved play_session_lpag_spectra structure is empty.');
end

%% Collect session-wise spectra and fit parameters
% Every Partners session behavior row is one independent analysis unit.
n_recordings = numel(play_session_lpag_spectra);
n_sessions = sum(arrayfun(@(x) numel(x.sessions), ...
    play_session_lpag_spectra));
frequency = play_session_lpag_spectra(1).frequency(:).';
n_frequency = numel(frequency);

welch_log_power = nan(n_sessions, n_frequency);
welch_aperiodic_fit = nan(n_sessions, n_frequency);
welch_gaussian_periodic = nan(n_sessions, n_frequency);
welch_raw_residual = nan(n_sessions, n_frequency);
welch_aperiodic_parameters = nan(n_sessions, 2);
welch_r_squared = nan(n_sessions, 1);
welch_fit_error = nan(n_sessions, 1);
welch_peak_parameters = cell(n_sessions, 1);

fourier_log_power = nan(n_sessions, n_frequency);
fourier_aperiodic_fit = nan(n_sessions, n_frequency);
fourier_gaussian_periodic = nan(n_sessions, n_frequency);
fourier_raw_residual = nan(n_sessions, n_frequency);
fourier_aperiodic_parameters = nan(n_sessions, 2);
fourier_r_squared = nan(n_sessions, 1);
fourier_fit_error = nan(n_sessions, 1);
fourier_peak_parameters = cell(n_sessions, 1);

session_name = cell(n_sessions, 1);
recording_index = nan(n_sessions, 1);
session_index = nan(n_sessions, 1);
lpag_channel = nan(n_sessions, 1);
lpag_lfp_row = nan(n_sessions, 1);
probe_number = nan(n_sessions, 1);
n_windows = nan(n_sessions, 1);

output_session_n = 0;
for recording_n = 1:n_recordings
    this_recording = play_session_lpag_spectra(recording_n);
    if ~isequal(this_recording.frequency(:).', frequency)
        error('Frequency vectors differ between saved sessions.');
    end

    for recording_session_n = 1:numel(this_recording.sessions)
        output_session_n = output_session_n + 1;
        this_session = this_recording.sessions(recording_session_n);

        session_name{output_session_n} = sprintf('%s session %d', ...
            this_recording.animal_name, recording_session_n);
        recording_index(output_session_n) = recording_n;
        session_index(output_session_n) = recording_session_n;
        lpag_channel(output_session_n) = this_recording.lpag_channel;
        lpag_lfp_row(output_session_n) = this_recording.lpag_lfp_row;
        probe_number(output_session_n) = ...
            this_recording.lpag_probe_number;
        n_windows(output_session_n) = this_session.n_windows;

        welch_log_power(output_session_n, :) = ...
            this_session.welch.log10_mean_power(:).';
        welch_aperiodic_fit(output_session_n, :) = ...
            this_session.welch.fooof.aperiodic_fit(:).';
        welch_gaussian_periodic(output_session_n, :) = ...
            this_session.welch.gaussian_periodic_fit(:).';
        welch_raw_residual(output_session_n, :) = ...
            this_session.welch.raw_aperiodic_subtracted(:).';
        welch_aperiodic_parameters(output_session_n, :) = ...
            this_session.welch.fooof.aperiodic_params(:).';
        welch_r_squared(output_session_n) = ...
            this_session.welch.fooof.r_squared;
        welch_fit_error(output_session_n) = ...
            this_session.welch.fooof.error;
        welch_peak_parameters{output_session_n} = ...
            this_session.welch.fooof.peak_params;

        fourier_log_power(output_session_n, :) = ...
            this_session.fourier.log10_mean_power(:).';
        fourier_aperiodic_fit(output_session_n, :) = ...
            this_session.fourier.fooof.aperiodic_fit(:).';
        fourier_gaussian_periodic(output_session_n, :) = ...
            this_session.fourier.gaussian_periodic_fit(:).';
        fourier_raw_residual(output_session_n, :) = ...
            this_session.fourier.raw_aperiodic_subtracted(:).';
        fourier_aperiodic_parameters(output_session_n, :) = ...
            this_session.fourier.fooof.aperiodic_params(:).';
        fourier_r_squared(output_session_n) = ...
            this_session.fourier.fooof.r_squared;
        fourier_fit_error(output_session_n) = ...
            this_session.fourier.fooof.error;
        fourier_peak_parameters{output_session_n} = ...
            this_session.fourier.fooof.peak_params;
    end
end

%% Delta-band summaries (1-4 Hz)
delta_index = frequency >= 1 & frequency <= 4;
welch_delta_gaussian = mean( ...
    welch_gaussian_periodic(:, delta_index), 2, 'omitnan');
welch_delta_raw = mean(welch_raw_residual(:, delta_index), 2, 'omitnan');
fourier_delta_gaussian = mean( ...
    fourier_gaussian_periodic(:, delta_index), 2, 'omitnan');
fourier_delta_raw = mean( ...
    fourier_raw_residual(:, delta_index), 2, 'omitnan');

session_summary = table(session_name, recording_index, session_index, ...
    lpag_channel, lpag_lfp_row, probe_number, n_windows, ...
    welch_aperiodic_parameters(:, 1), ...
    welch_aperiodic_parameters(:, 2), welch_r_squared, welch_fit_error, ...
    welch_delta_gaussian, welch_delta_raw, ...
    fourier_aperiodic_parameters(:, 1), ...
    fourier_aperiodic_parameters(:, 2), ...
    fourier_r_squared, fourier_fit_error, ...
    fourier_delta_gaussian, fourier_delta_raw, ...
    'VariableNames', {'Session', 'RecordingIndex', 'SessionIndex', ...
    'LPAGChannel', 'LPAGLFPRow', 'ProbeNumber', 'NWindows', ...
    'WelchOffset', 'WelchExponent', 'WelchR2', 'WelchError', ...
    'WelchDeltaGaussian', 'WelchDeltaRawResidual', ...
    'FourierOffset', 'FourierExponent', 'FourierR2', 'FourierError', ...
    'FourierDeltaGaussian', 'FourierDeltaRawResidual'});

%% Collapse multiple LPAG probe channels to one observation per session
% Channel-level values remain in session_summary and the matrices below.
% Group plots and SEMs use each recording/session row only once.
group_name = unique(session_name, 'stable');
n_group_sessions = numel(group_name);
group_welch_log_power = nan(n_group_sessions, n_frequency);
group_welch_aperiodic_fit = nan(n_group_sessions, n_frequency);
group_welch_gaussian = nan(n_group_sessions, n_frequency);
group_welch_raw = nan(n_group_sessions, n_frequency);
group_fourier_log_power = nan(n_group_sessions, n_frequency);
group_fourier_aperiodic_fit = nan(n_group_sessions, n_frequency);
group_fourier_gaussian = nan(n_group_sessions, n_frequency);
group_fourier_raw = nan(n_group_sessions, n_frequency);
group_n_channels = nan(n_group_sessions, 1);
group_n_windows = nan(n_group_sessions, 1);

for group_n = 1:n_group_sessions
    in_group = strcmp(session_name, group_name{group_n});
    group_n_channels(group_n) = sum(in_group);
    group_n_windows(group_n) = max(n_windows(in_group));
    group_welch_log_power(group_n, :) = ...
        mean(welch_log_power(in_group, :), 1, 'omitnan');
    group_welch_aperiodic_fit(group_n, :) = ...
        mean(welch_aperiodic_fit(in_group, :), 1, 'omitnan');
    group_welch_gaussian(group_n, :) = ...
        mean(welch_gaussian_periodic(in_group, :), 1, 'omitnan');
    group_welch_raw(group_n, :) = ...
        mean(welch_raw_residual(in_group, :), 1, 'omitnan');
    group_fourier_log_power(group_n, :) = ...
        mean(fourier_log_power(in_group, :), 1, 'omitnan');
    group_fourier_aperiodic_fit(group_n, :) = ...
        mean(fourier_aperiodic_fit(in_group, :), 1, 'omitnan');
    group_fourier_gaussian(group_n, :) = ...
        mean(fourier_gaussian_periodic(in_group, :), 1, 'omitnan');
    group_fourier_raw(group_n, :) = ...
        mean(fourier_raw_residual(in_group, :), 1, 'omitnan');
end

group_session_summary = table(group_name, group_n_channels, ...
    group_n_windows, ...
    mean(group_welch_gaussian(:, delta_index), 2, 'omitnan'), ...
    mean(group_welch_raw(:, delta_index), 2, 'omitnan'), ...
    mean(group_fourier_gaussian(:, delta_index), 2, 'omitnan'), ...
    mean(group_fourier_raw(:, delta_index), 2, 'omitnan'), ...
    'VariableNames', {'Session', 'NLPAGChannels', 'NWindows', ...
    'WelchDeltaGaussian', 'WelchDeltaRawResidual', ...
    'FourierDeltaGaussian', 'FourierDeltaRawResidual'});

%% Package complete analysis results
analysis_results = struct();
analysis_results.frequency = frequency;
analysis_results.delta_range = [1 4];
analysis_results.channel_session_summary = session_summary;
analysis_results.session_summary = group_session_summary;
analysis_results.animal_names = animal_names;

analysis_results.welch.log_power = welch_log_power;
analysis_results.welch.aperiodic_fit = welch_aperiodic_fit;
analysis_results.welch.gaussian_periodic_fit = welch_gaussian_periodic;
analysis_results.welch.raw_aperiodic_subtracted = welch_raw_residual;
analysis_results.welch.aperiodic_parameters = ...
    welch_aperiodic_parameters;
analysis_results.welch.peak_parameters = welch_peak_parameters;
analysis_results.welch.r_squared = welch_r_squared;
analysis_results.welch.fit_error = welch_fit_error;
analysis_results.welch.session_mean_log_power = group_welch_log_power;
analysis_results.welch.session_mean_aperiodic_fit = ...
    group_welch_aperiodic_fit;
analysis_results.welch.session_mean_gaussian = group_welch_gaussian;
analysis_results.welch.session_mean_raw_residual = group_welch_raw;

analysis_results.fourier.log_power = fourier_log_power;
analysis_results.fourier.aperiodic_fit = fourier_aperiodic_fit;
analysis_results.fourier.gaussian_periodic_fit = ...
    fourier_gaussian_periodic;
analysis_results.fourier.raw_aperiodic_subtracted = ...
    fourier_raw_residual;
analysis_results.fourier.aperiodic_parameters = ...
    fourier_aperiodic_parameters;
analysis_results.fourier.peak_parameters = fourier_peak_parameters;
analysis_results.fourier.r_squared = fourier_r_squared;
analysis_results.fourier.fit_error = fourier_fit_error;
analysis_results.fourier.session_mean_log_power = group_fourier_log_power;
analysis_results.fourier.session_mean_aperiodic_fit = ...
    group_fourier_aperiodic_fit;
analysis_results.fourier.session_mean_gaussian = ...
    group_fourier_gaussian;
analysis_results.fourier.session_mean_raw_residual = group_fourier_raw;

analysis_results.welch.group_mean_gaussian = ...
    mean(group_welch_gaussian, 1, 'omitnan');
analysis_results.welch.group_sem_gaussian = ...
    std(group_welch_gaussian, 0, 1, 'omitnan') ./ ...
    sqrt(sum(isfinite(group_welch_gaussian), 1));
analysis_results.welch.group_mean_raw_residual = ...
    mean(group_welch_raw, 1, 'omitnan');
analysis_results.welch.group_sem_raw_residual = ...
    std(group_welch_raw, 0, 1, 'omitnan') ./ ...
    sqrt(sum(isfinite(group_welch_raw), 1));

analysis_results.fourier.group_mean_gaussian = ...
    mean(group_fourier_gaussian, 1, 'omitnan');
analysis_results.fourier.group_sem_gaussian = ...
    std(group_fourier_gaussian, 0, 1, 'omitnan') ./ ...
    sqrt(sum(isfinite(group_fourier_gaussian), 1));
analysis_results.fourier.group_mean_raw_residual = ...
    mean(group_fourier_raw, 1, 'omitnan');
analysis_results.fourier.group_sem_raw_residual = ...
    std(group_fourier_raw, 0, 1, 'omitnan') ./ ...
    sqrt(sum(isfinite(group_fourier_raw), 1));

%% Plot original spectra and fitted aperiodic components
figure('Name', 'Play-session LPAG spectra and aperiodic fits');
subplot(1, 2, 1)
session_lines = plot(frequency, group_welch_log_power.', ...
    'Color', [0.8 0.8 0.8]);
hold on
mean_line = plot(frequency, mean(group_welch_log_power, 1, 'omitnan'), ...
    'k', 'LineWidth', 2);
aperiodic_line = plot(frequency, ...
    mean(group_welch_aperiodic_fit, 1, 'omitnan'), ...
    'b', 'LineWidth', 2);
xlabel('Frequency (Hz)')
ylabel('log_{10} PSD')
title('Welch')
legend([session_lines(1), mean_line, aperiodic_line], ...
    {'Sessions', 'Mean spectrum', 'Mean aperiodic fit'}, ...
    'Location', 'best')
box off

subplot(1, 2, 2)
session_lines = plot(frequency, group_fourier_log_power.', ...
    'Color', [0.8 0.8 0.8]);
hold on
mean_line = plot(frequency, ...
    mean(group_fourier_log_power, 1, 'omitnan'), ...
    'k', 'LineWidth', 2);
aperiodic_line = plot(frequency, ...
    mean(group_fourier_aperiodic_fit, 1, 'omitnan'), ...
    'b', 'LineWidth', 2);
xlabel('Frequency (Hz)')
ylabel('log_{10} PSD')
title('Direct Fourier periodogram')
legend([session_lines(1), mean_line, aperiodic_line], ...
    {'Sessions', 'Mean spectrum', 'Mean aperiodic fit'}, ...
    'Location', 'best')
box off

%% Plot both periodic estimates
figure('Name', 'Gaussian and raw aperiodic-subtracted periodic spectra');
subplot(1, 2, 1)
hold on
fill([frequency, fliplr(frequency)], ...
    [analysis_results.welch.group_mean_raw_residual + ...
     analysis_results.welch.group_sem_raw_residual, ...
     fliplr(analysis_results.welch.group_mean_raw_residual - ...
     analysis_results.welch.group_sem_raw_residual)], ...
    [0.7 0.7 0.7], 'EdgeColor', 'none', 'FaceAlpha', 0.3);
plot(frequency, analysis_results.welch.group_mean_raw_residual, ...
    'k', 'LineWidth', 2);
plot(frequency, analysis_results.welch.group_mean_gaussian, ...
    'm', 'LineWidth', 2);
yline(0, ':k')
xlabel('Frequency (Hz)')
ylabel('Power above aperiodic fit (log_{10})')
title('Welch')
legend({'Raw residual SEM', 'Raw residual', 'Gaussian fit'}, ...
    'Location', 'best')
box off

subplot(1, 2, 2)
hold on
fill([frequency, fliplr(frequency)], ...
    [analysis_results.fourier.group_mean_raw_residual + ...
     analysis_results.fourier.group_sem_raw_residual, ...
     fliplr(analysis_results.fourier.group_mean_raw_residual - ...
     analysis_results.fourier.group_sem_raw_residual)], ...
    [0.7 0.7 0.7], 'EdgeColor', 'none', 'FaceAlpha', 0.3);
plot(frequency, analysis_results.fourier.group_mean_raw_residual, ...
    'k', 'LineWidth', 2);
plot(frequency, analysis_results.fourier.group_mean_gaussian, ...
    'm', 'LineWidth', 2);
yline(0, ':k')
xlabel('Frequency (Hz)')
ylabel('Power above aperiodic fit (log_{10})')
title('Direct Fourier periodogram')
legend({'Raw residual SEM', 'Raw residual', 'Gaussian fit'}, ...
    'Location', 'best')
box off

%% Save analysis-ready summaries
output_file = fullfile(saving_folder, ...
    'play_session_lpag_periodic_aperiodic_analysis.mat');
save(output_file, 'analysis_results', '-v7.3');
disp(['Saved ', output_file])
