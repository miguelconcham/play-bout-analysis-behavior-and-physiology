%% Confidence intervals for aperiodic- and theta-subtracted spectra
confidence_level = 0.95;
ci_alpha = 1 - confidence_level;

welch_theta_removed_mean = mean( ...
    group_welch_aperiodic_theta_subtracted, 1, 'omitnan');
welch_theta_removed_n = sum( ...
    isfinite(group_welch_aperiodic_theta_subtracted), 1);
