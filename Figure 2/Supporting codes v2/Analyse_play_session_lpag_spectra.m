    group_welch_aperiodic_theta_subtracted, 0, 1, 'omitnan') ./ ...
    sqrt(welch_theta_removed_n);
welch_theta_removed_t = nan(size(welch_theta_removed_n));
valid_welch_ci = welch_theta_removed_n >= 2;
welch_theta_removed_t(valid_welch_ci) = tinv( ...
    1 - ci_alpha / 2, welch_theta_removed_n(valid_welch_ci) - 1);
