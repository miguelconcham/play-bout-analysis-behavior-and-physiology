function models = speed_peak_models(speed, peak, min_n)
%SPEED_PEAK_MODELS  Linear and logarithmic peak-frequency regressions.
%
% All three fits use the same rows: finite speed > 0 and finite peak
% frequency > 0. The models are
%
%   linear          PeakHz ~ Speed
%   log_frequency   log(PeakHz) ~ Speed
%   log_speed       PeakHz ~ log(Speed)
%
% log is the natural log. aic_hz is on the hertz scale. For the
% log-frequency model it is aic + 2*sum(log(peak)), the Jacobian that
% makes that AIC comparable to the models whose outcome is already in Hz.
% Speed is left in the units supplied by the caller. A session passes raw
% pixels per second; the pooled linear models pass the within-animal
% z-score.

speed = double(speed(:));
peak = double(peak(:));
if numel(speed) ~= numel(peak)
    error('speed_peak_models:size', ...
        'speed and peak frequency must have one value per row.');
end
if nargin < 3 || isempty(min_n)
    min_n = 3;
end

keep = isfinite(speed) & isfinite(peak) & speed > 0 & peak > 0;
speed = speed(keep);
peak = peak(keep);
models = [ ...
    one_model('linear', 'PeakHz ~ Speed', 'PeakHz', 'Speed', ...
        speed, peak, min_n, peak), ...
    one_model('log_frequency', 'log(PeakHz) ~ Speed', 'log(PeakHz)', 'Speed', ...
        speed, log(peak), min_n, peak), ...
    one_model('log_speed', 'PeakHz ~ log(Speed)', 'PeakHz', 'log(Speed)', ...
        log(speed), peak, min_n, peak)];
end

function model = one_model(name, formula, outcome, predictor, x, y, min_n, peak_hz)
fit = speed_peak_ols(x, y, min_n);
aic_hz = fit.aic;
if fit.ok && strcmp(name, 'log_frequency')
    aic_hz = fit.aic + 2 * sum(log(peak_hz(:)));
end
model = struct( ...
    'name', name, ...
    'formula', formula, ...
    'outcome', outcome, ...
    'predictor', predictor, ...
    'ok', fit.ok, ...
    'n', fit.n, ...
    'intercept', fit.intercept, ...
    'slope', fit.slope, ...
    'intercept_se', fit.intercept_se, ...
    'slope_se', fit.slope_se, ...
    'intercept_p', fit.intercept_p, ...
    'slope_p', fit.slope_p, ...
    'r_squared', fit.r_squared, ...
    'sigma', fit.sigma, ...
    'aic', fit.aic, ...
    'aic_hz', aic_hz);
end
