function test_mixture_measurements_for_separated_centers()
centers = [3 + 0.2 * randn(40, 1); 30 + 0.2 * randn(40, 1)];
posterior_weight = [repmat([0.99 0.01], 40, 1); repmat([0.01 0.99], 40, 1)];
means = [3; 30];
sds = [0.2; 0.2];
weights = [0.5; 0.5];
log_density = zeros(numel(centers), 1);
for center_n = 1:numel(centers)
    distance = ((centers(center_n) - means) ./ sds).^2;
    log_component = log(weights) - log(sds) - 0.5 * log(2 * pi) - 0.5 * distance;
    peak = max(log_component);
    log_density(center_n) = peak + log(sum(exp(log_component - peak)));
end
negative_log_likelihood = -sum(log_density);
n_parameters = 5;
fit_info = struct( ...
    'aic', 2 * negative_log_likelihood + 2 * n_parameters, ...
    'bic', 2 * negative_log_likelihood + n_parameters * log(numel(centers)), ...
    'negative_log_likelihood', negative_log_likelihood, ...
    'converged', true, ...
    'num_iterations', 12, ...
    'replicates', 2, ...
    'regularization', 1e-4, ...
    'minimum_effective_membership', 3, ...
    'shared_covariance', 0);
[scalars, components] = gaussian_mixture_measurements( ...
    means, sds, weights, centers, posterior_weight, fit_info);
assert(scalars.Eligible, 'Separated components were not eligible.');
assert(scalars.Entropy < 10, ...
    'Nearly hard assignments still had a large entropy.');
assert(scalars.MinimumNeighborAshmanD > 2, ...
    'Centers 27 Hz apart were not separated by Ashman D.');
assert(abs(scalars.MinimumNeighborSeparationHz - 27) < 1e-9, ...
    'The neighbor separation was not 27 Hz.');
assert(height(components) == 2, ...
    'The two components were not both stored.');
assert(isfinite(scalars.KSDistance) && isfinite(scalars.ChiSquare), ...
    'Goodness-of-fit was not stored.');
end

