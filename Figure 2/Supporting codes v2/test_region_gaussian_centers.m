function test_region_gaussian_centers()
%TEST_REGION_GAUSSIAN_CENTERS  Region labels, BIC choice, and the figure.
%
% No experiment files. The mixture fit itself runs when fitgmdist exists.

this_dir = fileparts(mfilename('fullpath'));
if ~isempty(this_dir)
    addpath(this_dir);
end

test_region_membership();
test_criterion_selection();
test_search_plan_caps_gaussians_and_restarts();
test_remaining_time_scales_with_work();
test_saved_region_fit_is_recognized();
test_short_samples_are_not_fitted();
test_distribution_figure();
if exist('fitgmdist', 'file') == 2
    test_separated_centers_select_two_components();
else
    fprintf(['fitgmdist is not on the path, so the mixture fit was ' ...
        'not executed.\n']);
end
disp('test_region_gaussian_centers passed.')
end

function test_region_membership()
spectra = fake_probe_spectra();
regions = {'DR', 'VLPAG', 'LPAG', 'DLPAG', 'SC'};
[peak_table, regions_out] = region_gaussian_center_table( ...
    spectra, regions, {'Fourier', 'Welch'}, [], 4);

assert(isequal(regions_out, ...
    {'DR', 'VLPAG', 'LPAG', 'DLPAG', 'SupCol'}), ...
    'SC was not returned as SupCol in the requested order.');
assert(isequal(unique(peak_table.Region, 'stable'), regions_out(:)), ...
    'Collected regions did not follow the requested list.');
assert(all(peak_table.RecordingIndex == 4), ...
    'The recording index was not stamped on the peaks.');
assert(ismember('Welch', peak_table.Method) && ...
    ismember('Fourier', peak_table.Method), ...
    'Both spectral methods were not collected.');

dr = centers_for(peak_table, 'DR', 'Fourier');
assert(isequal(dr, 4), 'The non-finite DR center was kept.');
vlpag = centers_for(peak_table, 'VLPAG', 'Fourier');
assert(isequal(sort(vlpag(:).'), [8 30]), ...
    'VLPAG took peaks that belong only to LPAG.');
lpag = centers_for(peak_table, 'LPAG', 'Fourier');
assert(isequal(sort(lpag(:).'), [7 8 30]), ...
    'The shared VLPAG/LPAG channel did not contribute to LPAG.');
dlpag = centers_for(peak_table, 'DLPAG', 'Fourier');
assert(isequal(dlpag, 12), 'DLPAG was merged into LPAG.');
supcol = centers_for(peak_table, 'SupCol', 'Fourier');
assert(isequal(sort(supcol(:).'), [6 20]), ...
    'SC and SupCol were not pooled, or the second session was dropped.');
assert(~any(strcmp(peak_table.Area, 'InfCol')), ...
    'InfCol entered a requested region.');

failed = false;
try
    region_gaussian_center_table(spectra, {'InfCol'}, 'Fourier', [], 1);
    failed = true;
catch ME
    assert(contains(ME.message, 'Unknown region'), ME.message);
end
assert(~failed, 'An unknown region was accepted.');

[empty_table, empty_regions] = region_gaussian_center_table(struct( ...
    'animal_name', 'none', 'n_sessions', 0), {'SC'}, 'Fourier');
assert(isempty(empty_table), 'A recording with no sessions returned peaks.');
assert(isequal(empty_regions, {'SupCol'}), ...
    'A recording with no sessions did not canonicalise SC.');
assert(ismember('CenterFrequency', empty_table.Properties.VariableNames), ...
    'The empty peak table lost its center-frequency column.');
end

function test_criterion_selection()
counts = (1:3).';
aic = [10; 7; 6];
bic = [10; 8; 9];
eligible = [true; true; true];
assert(select_gaussian_mixture_count(counts, bic, eligible) == 2, ...
    'BIC did not keep the lower eligible value.');
assert(select_gaussian_mixture_count(counts, aic, eligible) == 3, ...
    'AIC did not keep its own minimum when BIC disagrees.');

eligible(2) = false;
assert(select_gaussian_mixture_count(counts, bic, eligible) == 3, ...
    'An ineligible BIC minimum was selected.');
assert(isnan(select_gaussian_mixture_count(counts, bic, false(3, 1))), ...
    'A sample with no eligible model returned a component count.');
end

function test_search_plan_caps_gaussians_and_restarts()
options = struct('max_components', 10, 'replicates', 50, ...
    'large_sample_centers', 500, 'large_sample_replicates', 10, ...
    'minimum_observations_per_component', 5);
large = gaussian_mixture_search_plan(10000, 9000, options);
assert(large.max_components_tested == 10, ...
    'A large sample tested more than the Gaussian cap.');
assert(large.replicates == 10, ...
    'A large sample kept all 50 restarts.');
assert(large.restarts_reduced, ...
    'The large-sample restart reduction was not recorded.');
assert(abs(large.work_units - 10000 * 10 * sum(1:10)) < 1e-6, ...
    'Work units are not centers times restarts times component counts.');

small = gaussian_mixture_search_plan(80, 80, options);
assert(small.max_components_tested == 10, ...
    'Eighty centers did not reach the cap of 10.');
assert(small.replicates == 50, ...
    'A small sample did not keep the mid-LPAG restart count.');
assert(~small.restarts_reduced, ...
    'A small sample was marked as restart-reduced.');

limited = gaussian_mixture_search_plan(30, 30, options);
assert(limited.max_components_tested == 6, ...
    'Thirty centers were not limited to one component per five centers.');
assert(strcmp(format_search_duration(45), '45 s'), ...
    'A short duration was not reported in seconds.');
assert(contains(format_search_duration(125), 'min'), ...
    'A two-minute duration was not reported in minutes.');

defaults = gaussian_mixture_options(struct());
assert(defaults.max_components == 20, ...
    'The default Gaussian cap is not 20.');
assert(defaults.replicates == 50 && defaults.large_sample_replicates == 50, ...
    'The default search does not keep 50 restarts for a large region.');
robust = gaussian_mixture_search_plan(10000, 9000, defaults);
assert(robust.max_components_tested == 20, ...
    'The robust search did not test 20 Gaussians.');
assert(robust.replicates == 50 && ~robust.restarts_reduced, ...
    'The robust search reduced the restart count.');
end

function test_remaining_time_scales_with_work()
seconds = mixture_remaining_seconds(10, 100, 300);
assert(abs(seconds - 30) < 1e-9, ...
    'Remaining time did not scale with unfinished work.');
assert(isnan(mixture_remaining_seconds(10, 0, 300)), ...
    'A clock with no finished work returned a finite time.');
end

function test_saved_region_fit_is_recognized()
assert(~region_mixture_already_saved(struct('fit', [])), ...
    'An empty fit was treated as saved.');
assert(~region_mixture_already_saved(struct('name', 'SupCol', 'fit', [])), ...
    'A missing SupCol fit was treated as saved.');
assert(region_mixture_already_saved(struct('fit', struct('status', 'fitted'))), ...
    'A fitted region was not kept.');
assert(region_mixture_already_saved(struct('fit', struct( ...
    'status', 'fewer than 5 finite center frequencies'))), ...
    'A completed skip was treated as missing.');
end

function test_short_samples_are_not_fitted()
result = fit_gaussian_center_mixture([1; 2; 3], [0.1 45], struct( ...
    'selection_criterion', 'BIC'));
assert(~strcmp(result.status, 'fitted'), ...
    'Three centers were fit despite the five-center minimum.');
assert(isempty(result.model_selection) || height(result.model_selection) == 0, ...
    'A skipped fit still stored component criteria.');
assert(strcmp(result.selection_criterion, 'BIC'), ...
    'The default criterion was not BIC.');
end

function test_distribution_figure()
frequency = [0.1 45];
first = fitted_region('DR', [3; 3.4; 28; 31], 2, [3.2; 29.5]);
second = fitted_region('LPAG', [1; 2; 3], NaN, zeros(0, 1));
second.fit.status = 'fewer than 5 finite center frequencies';
second.n_channels = 1;
second.n_sessions = 1;
figure_handle = plot_region_gaussian_centers( ...
    [first; second], frequency, 'BIC', 8, 1, 'Fourier');
histograms = findall(figure_handle, 'Type', 'histogram');
assert(numel(histograms) == 2, ...
    'Each region did not draw its center-frequency distribution.');
close(figure_handle);
end

function test_separated_centers_select_two_components()
previous_rng = rng;
rng(2, 'twister');
centers = [3 + 0.35 * randn(60, 1); 32 + 0.7 * randn(60, 1)];
rng(previous_rng);

options = struct( ...
    'selection_criterion', 'BIC', ...
    'max_components', 4, ...
    'replicates', 4, ...
    'max_iter', 500, ...
    'random_seed', 1);
first = fit_gaussian_center_mixture(centers, [0.1 45], options);
second = fit_gaussian_center_mixture(centers, [0.1 45], options);
assert(strcmp(first.status, 'fitted'), first.status);
assert(first.best_n_components == 2, ...
    'Two separated center clusters were not the BIC model.');
assert(abs(first.best_component_table.MeanHz(1) - 3) < 1, ...
    'The low-frequency component moved away from 3 Hz.');
assert(abs(first.best_component_table.MeanHz(2) - 32) < 1.5, ...
    'The high-frequency component moved away from 32 Hz.');
assert(max(abs(first.mixture_density - ...
    sum(first.component_density, 2))) < 1e-12, ...
    'The mixture density is not the sum of its components.');
assert(isequal(first.best_component_table.MeanHz, ...
    second.best_component_table.MeanHz), ...
    'The same seed did not repeat the component means.');

options.selection_criterion = 'AIC';
aic_fit = fit_gaussian_center_mixture(centers, [0.1 45], options);
assert(strcmp(aic_fit.selection_criterion, 'AIC'), ...
    'The AIC switch was stored as BIC.');
assert(strcmp(aic_fit.status, 'fitted'), aic_fit.status);
end

function centers = centers_for(peak_table, region_name, method_name)
keep = strcmp(peak_table.Region, region_name) & ...
    strcmp(peak_table.Method, method_name);
centers = peak_table.CenterFrequency(keep);
end

function region_result = fitted_region(name, centers, best_n, means)
region_result = struct( ...
    'name', name, ...
    'n_peaks', numel(centers), ...
    'n_channels', 2, ...
    'n_sessions', 1, ...
    'fit', []);
density_frequency = linspace(0.1, 45, 40).';
n_components = numel(means);
component_density = zeros(numel(density_frequency), n_components);
for component_n = 1:n_components
    component_density(:, component_n) = 0.5 * exp(-0.5 * ( ...
        (density_frequency - means(component_n)) / 1).^2) / sqrt(2 * pi);
end
model_selection = table([1; 2], [20; 14], [24; 16], [true; true], ...
    'VariableNames', {'NComponents', 'AIC', 'BIC', 'Eligible'});
if ~isfinite(best_n)
    model_selection = model_selection([], :);
    component_density = zeros(0, 0);
    density_frequency = zeros(0, 1);
    component_table = table(zeros(0, 1), zeros(0, 1), zeros(0, 1), ...
        zeros(0, 1), 'VariableNames', ...
        {'Component', 'MeanHz', 'SDHz', 'Weight'});
    status = 'not fitted';
else
    component_table = table((1:n_components).', means(:), ...
        ones(n_components, 1), repmat(1 / n_components, n_components, 1), ...
        'VariableNames', {'Component', 'MeanHz', 'SDHz', 'Weight'});
    status = 'fitted';
end
region_result.fit = struct( ...
    'status', status, ...
    'selection_criterion', 'BIC', ...
    'center_frequencies', centers(:), ...
    'model_selection', model_selection, ...
    'best_n_components', best_n, ...
    'best_component_table', component_table, ...
    'density_frequency', density_frequency, ...
    'component_density', component_density, ...
    'mixture_density', sum(component_density, 2));
end

function spectra = fake_probe_spectra()
area = {'DR'; 'VLPAG, LPAG'; 'LPAG'; 'DLPAG'; 'SC'; 'SupCol'; 'InfCol'};
spectra = struct();
spectra.animal_name = 'B1D1 1007 Dual';
spectra.frequency = (0.1:0.1:45).';
spectra.n_sessions = 2;
spectra.channel_table = table((1:7).', (2:8).', ones(7, 1), ...
    (100:100:700).', area, ...
    'VariableNames', {'Channel', 'LFPRow', 'ProbeNumber', 'Yum', 'Area'});

session_one = fake_session({ ...
    [4 1 0.5; NaN 1 0.2], ...
    [8 1 0.4; 30 0.3 1], ...
    [7 0.8 0.3], ...
    [12 0.5 0.8], ...
    [20 0.4 1], ...
    zeros(0, 3), ...
    [3 1 0.2]});
session_two = fake_session({ ...
    zeros(0, 3), ...
    zeros(0, 3), ...
    [], ...
    zeros(0, 3), ...
    zeros(0, 3), ...
    [6 0.5 0.4], ...
    [9 0.2 0.3]});
spectra.sessions = [session_one; session_two];
end

