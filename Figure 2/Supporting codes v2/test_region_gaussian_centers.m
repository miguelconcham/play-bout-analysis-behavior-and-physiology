function test_separated_centers_select_two_components()
previous_rng = rng;
rng(2, 'twister');
centers = [3 + 0.35 * randn(60, 1); 32 + 0.7 * randn(60, 1)];
rng(previous_rng);

options = struct( ...
    'selection_criterion', 'BIC', ...
    'max_components', 4, ...
    'replicates', 4, ...
    'max_iter', 500, ...
    'random_seed', 1);
first = fit_gaussian_center_mixture(centers, [0.1 45], options);
second = fit_gaussian_center_mixture(centers, [0.1 45], options);
assert(strcmp(first.status, 'fitted'), first.status);
assert(first.best_n_components == 2, ...
    'Two separated center clusters were not the BIC model.');
assert(abs(first.best_component_table.MeanHz(1) - 3) < 1, ...
    'The low-frequency component moved away from 3 Hz.');
assert(abs(first.best_component_table.MeanHz(2) - 32) < 1.5, ...
    'The high-frequency component moved away from 32 Hz.');
assert(max(abs(first.mixture_density - ...
    sum(first.component_density, 2))) < 1e-12, ...
    'The mixture density is not the sum of its components.');
assert(isequal(first.best_component_table.MeanHz, ...
    second.best_component_table.MeanHz), ...
    'The same seed did not repeat the component means.');

options.selection_criterion = 'AIC';
aic_fit = fit_gaussian_center_mixture(centers, [0.1 45], options);
assert(strcmp(aic_fit.selection_criterion, 'AIC'), ...
    'The AIC switch was stored as BIC.');
assert(strcmp(aic_fit.status, 'fitted'), aic_fit.status);
end

function centers = centers_for(peak_table, region_name, method_name)
keep = strcmp(peak_table.Region, region_name) & ...
    strcmp(peak_table.Method, method_name);
centers = peak_table.CenterFrequency(keep);
end

function region_result = fitted_region(name, centers, best_n, means)
region_result = struct( ...
    'name', name, ...
    'n_peaks', numel(centers), ...
    'n_channels', 2, ...
    'n_sessions', 1, ...
    'fit', []);
density_frequency = linspace(0.1, 45, 40).';
n_components = numel(means);
component_density = zeros(numel(density_frequency), n_components);
for component_n = 1:n_components
    component_density(:, component_n) = 0.5 * exp(-0.5 * ( ...
        (density_frequency - means(component_n)) / 1).^2) / sqrt(2 * pi);
end
model_selection = table([1; 2], [20; 14], [24; 16], [true; true], ...
    'VariableNames', {'NComponents', 'AIC', 'BIC', 'Eligible'});
if ~isfinite(best_n)
    model_selection = model_selection([], :);
    component_density = zeros(0, 0);
    density_frequency = zeros(0, 1);
    component_table = table(zeros(0, 1), zeros(0, 1), zeros(0, 1), ...
        zeros(0, 1), 'VariableNames', ...
        {'Component', 'MeanHz', 'SDHz', 'Weight'});
    status = 'not fitted';
else
    component_table = table((1:n_components).', means(:), ...
        ones(n_components, 1), repmat(1 / n_components, n_components, 1), ...
        'VariableNames', {'Component', 'MeanHz', 'SDHz', 'Weight'});
    status = 'fitted';
end
region_result.fit = struct( ...
    'status', status, ...
    'selection_criterion', 'BIC', ...
    'center_frequencies', centers(:), ...
    'model_selection', model_selection, ...
    'best_n_components', best_n, ...
    'best_component_table', component_table, ...
    'density_frequency', density_frequency, ...
    'component_density', component_density, ...
    'mixture_density', sum(component_density, 2));
end

