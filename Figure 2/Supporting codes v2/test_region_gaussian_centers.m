nll = [200; 100; 90; 88];
n_parameters = [2; 5; 8; 11];
n_observations = repmat(400, 4, 1);
aic = 2 * nll + 2 * n_parameters;
bic = 2 * nll + n_parameters * log(400);
entropy = [0; 1; 20; 40];
completed = -nll - entropy;
model_selection = table(k, aic, bic, nll, true(4, 1), entropy, ...
    n_parameters, n_observations, completed, ...
    [NaN; 6; 3; 1], [NaN; 0.05; 0.2; 0.9], ...
    [0.20; 0.08; 0.05; 0.049], ...
    'VariableNames', {'NComponents', 'AIC', 'BIC', ...
    'NegativeLogLikelihood', 'Eligible', 'Entropy', 'NParameters', ...
    'NObservations', 'CompletedLogLikelihood', ...
    'MinimumNeighborAshmanD', 'MaximumPairBhattacharyya', 'KSDistance'});
selection = select_region_gaussian_criteria(model_selection, struct( ...
    'elbow_fraction', 0.05, ...
    'ashman_d_minimum', 2, ...
    'bhattacharyya_maximum', 0.5, ...
    'gof_relative_tolerance', 0.1));
assert(selected_count(selection, 'AIC') == 3, ...
    'AIC did not select 3 components.');
assert(selected_count(selection, 'BIC') == 3, ...
    'BIC did not select 3 components.');
assert(selected_count(selection, 'ICL') == 2, ...
    'ICL did not stop before the BIC minimum.');
assert(selected_count(selection, 'NEC') == 2, ...
    'NEC did not select the most separated count.');
assert(selected_count(selection, 'ElbowBICSuccessive') == 2, ...
    'The successive BIC elbow followed the slow tail.');
assert(selected_count(selection, 'ElbowBICCumulative') == 2, ...
    'The cumulative BIC elbow followed the slow tail.');
assert(selected_count(selection, 'AshmanSeparation') == 3, ...
    'Ashman D kept an overlapping component.');
assert(selected_count(selection, 'BhattacharyyaOverlap') == 3, ...
    'Bhattacharyya overlap kept an overlapping component.');
assert(selected_count(selection, 'KSDistanceWithinTolerance') == 3, ...
    'The KS tolerance did not keep the smaller adequate count.');
assert(selected_count(selection, 'SlopeHeuristicJump') == 3, ...
    'The dimension jump did not select 3 components.');
assert(selected_count(selection, 'SlopeHeuristicRegression') == 3, ...
    'The slope regression did not select 3 components.');

linear = table(k, [100; 98; 96; 94], [2; 5; 8; 11], true(4, 1), ...
    'VariableNames', {'NComponents', 'NegativeLogLikelihood', ...
    'NParameters', 'Eligible'});
linear_selection = select_region_gaussian_criteria(linear);
assert(selected_count(linear_selection, 'SlopeHeuristicRegression') == 1, ...
    'A linear likelihood descent was not sent to one component.');

likelihood_only = model_selection(:, {'NComponents', 'AIC', 'BIC', ...
    'NegativeLogLikelihood', 'Eligible'});
older = select_region_gaussian_criteria(likelihood_only, struct( ...
    'n_observations', 400));
assert(selected_count(older, 'BIC') == 3, ...
    'An older save could not select by BIC.');
icl_index = find(strcmp(older.Criterion, 'ICL'), 1);
assert(~older.Available(icl_index), ...
    'ICL ran without a stored entropy.');
assert(contains(older.Note{icl_index}, 'unavailable'), ...
    'The missing entropy was not described as unavailable.');
end

function test_saved_criterion_redraws_the_mixture()
model_selection = criterion_measurement_table();
components = table([2; 2; 3; 3; 3], [30; 4; 15; 4; 30], ...
    [1; 1.2; 1; 0.8; 1.1], [0.4; 0.6; 0.2; 0.5; 0.3], ...
    'VariableNames', {'NComponents', 'MeanHz', 'SDHz', 'Weight'});
region = stored_region(model_selection, components, 3);
[redrawn, outcome] = region_mixture_for_criterion( ...
    region, 'ICL', [0.1 45], struct());
assert(outcome.applied, outcome.note);
assert(outcome.selected_n == 2, 'ICL did not select 2 components.');
assert(redrawn.fit.best_n_components == 2, ...
    'The drawn mixture stayed on the BIC count.');
assert(isequal(redrawn.fit.best_component_table.MeanHz, [4; 30]), ...
    'The two-component curves were not rebuilt from stored parameters.');
assert(size(redrawn.fit.component_density, 2) == 2, ...
    'The rebuilt mixture still had the BIC components.');
assert(numel(redrawn.fit.density_frequency) == 1000, ...
    'The rebuilt frequency grid is not 1,000 points.');
assert(max(abs(redrawn.fit.mixture_density - ...
    sum(redrawn.fit.component_density, 2))) < 1e-12, ...
    'The rebuilt mixture is not the sum of its components.');

older = region;
older.fit = rmfield(older.fit, 'component_parameters');
saved_density = older.fit.mixture_density;
[kept, bic_outcome] = region_mixture_for_criterion( ...
    older, 'BIC', [0.1 45], struct());
assert(bic_outcome.applied, bic_outcome.note);
assert(kept.fit.best_n_components == 3, ...
    'BIC did not keep the stored component count.');
assert(isequal(kept.fit.mixture_density, saved_density), ...
    'A matching saved count rebuilt curves that were not stored.');

[blocked, elbow_outcome] = region_mixture_for_criterion( ...
    older, 'ElbowBICSuccessive', [0.1 45], struct());
assert(~elbow_outcome.applied, ...
    'A different count was drawn without stored parameters.');
assert(contains(elbow_outcome.note, 'not stored'), elbow_outcome.note);
assert(blocked.fit.best_n_components == 3, ...
    'A blocked redraw changed the saved component count.');

likelihood_only = model_selection(:, {'NComponents', 'AIC', 'BIC', ...
    'NegativeLogLikelihood', 'Eligible'});
without_entropy = stored_region(likelihood_only, components, 3);
[~, icl_outcome] = region_mixture_for_criterion( ...
    without_entropy, 'ICL', [0.1 45], struct());
assert(~icl_outcome.applied, 'ICL ran without a stored entropy.');
assert(contains(icl_outcome.note, 'unavailable'), icl_outcome.note);

[unknown, unknown_outcome] = region_mixture_for_criterion( ...
    region, 'NotARule', [0.1 45], struct());
assert(unknown.fit.best_n_components == 3, ...
    'An unknown rule cleared the saved component count.');
assert(~unknown_outcome.applied, 'An unknown rule was drawn.');
assert(contains(unknown_outcome.note, 'unknown'), unknown_outcome.note);
end

