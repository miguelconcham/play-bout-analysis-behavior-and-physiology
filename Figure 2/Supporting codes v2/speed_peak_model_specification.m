function spec = speed_peak_model_specification()
%SPEED_PEAK_MODEL_SPECIFICATION  Regression choices saved with the analysis.
%
% These choices belong to Analyze_speed_peak_frequency. The estimate
% parameters stay in speed_peak_options.

spec = struct();
spec.per_session_models = { ...
    'PeakHz ~ Speed'; ...
    'log(PeakHz) ~ Speed'; ...
    'PeakHz ~ log(Speed)'};
spec.log_base = 'natural';
spec.per_session_speed = ['Pixels per second. The camera scale is constant ' ...
    'inside one video, so a session slope stays on that scale.'];
spec.pooled_formula = ['outcome ~ predictor + (1|Animal) + (1|Session), ' ...
    'fit by maximum likelihood'];
spec.session_id = ['animal, partner, and session index. Channels of one ' ...
    'behavioral session share the session intercept.'];
spec.comparison_rows = ['speed > 0, peak frequency > 0, and a finite ' ...
    'within-animal speed z-score. All three functional forms use those rows.'];
spec.linear_speed_normalization = ['Within-animal z-score. The mean and SD ' ...
    'are the unique animal-session-bin speeds, including bins with a missing ' ...
    'peak. Duplicate channels share a speed and count once in the SD.'];
spec.log_frequency_speed_normalization = spec.linear_speed_normalization;
spec.log_speed_normalization = ['Natural log of pixels per second. A ' ...
    'multiplicative per-animal pixel scale becomes an additive animal intercept.'];
spec.why_zscore_linear_speed = ['A per-animal pixel scale multiplies a linear ' ...
    'speed slope. The animal intercept estimates a baseline peak frequency, so ' ...
    'the pooled PeakHz and log(PeakHz) models use the within-animal z-score. ' ...
    'On log speed, that scale is absorbed by the animal intercept, so ' ...
    'PeakHz ~ log(Speed) keeps raw pixels per second.'];
spec.aic_hz = ['AIC on the hertz scale. For log(PeakHz), AIC_Hz = AIC_log + ' ...
    '2*sum(log(PeakHz)), the Jacobian of the natural log. Per-session AIC ' ...
    'counts the intercept, slope, and error variance, as fitlm does.'];
spec.min_rows = 'min_bins_for_correlation from the estimate parameters';
end
