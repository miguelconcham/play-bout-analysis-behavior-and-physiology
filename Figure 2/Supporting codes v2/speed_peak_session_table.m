function [peak_table, correlation_table] = speed_peak_session_table(recordings)
%SPEED_PEAK_SESSION_TABLE  One row per session, channel, and speed bin.
%
% peak_table holds the delta and theta peak frequencies against the speed
% of the windows that entered that bin. correlation_table holds the
% within-session Pearson and Spearman correlations, with Welch and Fourier
% on separate rows. Sessions stay separate; nothing is pooled here.

peak_names = {'Animal', 'AreaTableName', 'Partner', 'SessionIndex', ...
    'SessionSource', 'Probe', 'LPAGChannel', 'Bin', 'NSpeedSamples', ...
    'SpeedFraction', 'SpeedMin', 'SpeedMedian', 'SpeedMax', 'NWindows', ...
    'SpectrumSpeed', 'WelchDeltaCF', 'WelchDeltaPower', 'WelchThetaCF', ...
    'WelchThetaPower', 'WelchRSquared', 'FourierDeltaCF', ...
    'FourierDeltaPower', 'FourierThetaCF', 'FourierThetaPower', ...
    'FourierRSquared'};
peak_types = {'cell', 'cell', 'double', 'double', ...
    'cell', 'double', 'double', 'double', 'double', ...
    'double', 'double', 'double', 'double', 'double', ...
    'double', 'double', 'double', 'double', ...
    'double', 'double', 'double', ...
    'double', 'double', 'double', ...
    'double'};
correlation_names = {'Animal', 'AreaTableName', 'Partner', 'SessionIndex', ...
    'SessionSource', 'Probe', 'LPAGChannel', 'Method', ...
    'NSpeedBins', 'BinsWithinRequestedFractions', 'NDelta', ...
    'PearsonDelta', 'PearsonDeltaP', 'SpearmanDelta', 'SpearmanDeltaP', ...
    'NTheta', 'PearsonTheta', 'PearsonThetaP', 'SpearmanTheta', ...
    'SpearmanThetaP', 'NDeltaTheta', 'PearsonDeltaTheta', ...
    'PearsonDeltaThetaP', 'SpearmanDeltaTheta', 'SpearmanDeltaThetaP'};
correlation_types = {'cell', 'cell', 'double', 'double', ...
    'cell', 'double', 'double', 'cell', ...
    'double', 'double', 'double', ...
    'double', 'double', 'double', 'double', ...
    'double', 'double', 'double', 'double', ...
    'double', 'double', 'double', ...
    'double', 'double', 'double'};

peak_rows = cell(0, numel(peak_names));
correlation_rows = cell(0, numel(correlation_names));
if isempty(recordings)
    peak_table = empty_table(peak_names, peak_types);
    correlation_table = empty_table(correlation_names, correlation_types);
    return
end

for recording_n = 1:numel(recordings)
    recording = recordings(recording_n);
    if ~isfield(recording, 'sessions') || isempty(recording.sessions)
        continue
    end
    for session_n = 1:numel(recording.sessions)
        session = recording.sessions(session_n);
        n_bins = numel(session.speed_bins);
        for bin_n = 1:n_bins
            speed_bin = session.speed_bins(bin_n);
            peak_rows(end + 1, :) = { ...
                recording.animal_name, ...
                recording.animal_area_table_name, ...
                session.partner_index, ...
                session.session_index, ...
                session.session_source, ...
                recording.lpag_probe_number, ...
                recording.lpag_channel, ...
                bin_n, ...
                speed_bin.n_speed_samples, ...
                speed_bin.fraction_of_speed_samples, ...
                speed_bin.speed_min, ...
                speed_bin.speed_median, ...
                speed_bin.speed_max, ...
                speed_bin.n_windows, ...
                speed_bin.spectrum_speed, ...
                session.welch.delta_peak(bin_n).center_frequency, ...
                session.welch.delta_peak(bin_n).power, ...
                session.welch.theta_peak(bin_n).center_frequency, ...
                session.welch.theta_peak(bin_n).power, ...
                session.welch.r_squared(bin_n), ...
                session.fourier.delta_peak(bin_n).center_frequency, ...
                session.fourier.delta_peak(bin_n).power, ...
                session.fourier.theta_peak(bin_n).center_frequency, ...
                session.fourier.theta_peak(bin_n).power, ...
                session.fourier.r_squared(bin_n)}; %#ok<AGROW>
        end

        methods = {'Welch', 'Fourier'};
        stats = {session.correlation_welch, session.correlation_fourier};
        for method_n = 1:numel(methods)
            this_stats = stats{method_n};
            correlation_rows(end + 1, :) = { ...
                recording.animal_name, ...
                recording.animal_area_table_name, ...
                session.partner_index, ...
                session.session_index, ...
                session.session_source, ...
                recording.lpag_probe_number, ...
                recording.lpag_channel, ...
                methods{method_n}, ...
                numel(session.speed_bins), ...
                double(session.bins_within_requested_fractions), ...
                this_stats.n_delta, ...
                this_stats.pearson_delta, ...
                this_stats.pearson_delta_p, ...
                this_stats.spearman_delta, ...
                this_stats.spearman_delta_p, ...
                this_stats.n_theta, ...
                this_stats.pearson_theta, ...
                this_stats.pearson_theta_p, ...
                this_stats.spearman_theta, ...
                this_stats.spearman_theta_p, ...
                this_stats.n_delta_theta, ...
                this_stats.pearson_delta_theta, ...
                this_stats.pearson_delta_theta_p, ...
                this_stats.spearman_delta_theta, ...
                this_stats.spearman_delta_theta_p}; %#ok<AGROW>
        end
    end
end

if isempty(peak_rows)
    peak_table = empty_table(peak_names, peak_types);
else
    peak_table = cell2table(peak_rows, 'VariableNames', peak_names);
end
if isempty(correlation_rows)
    correlation_table = empty_table(correlation_names, correlation_types);
else
    correlation_table = cell2table(correlation_rows, 'VariableNames', correlation_names);
end
end

function result = empty_table(names, types)
result = table('Size', [0, numel(names)], ...
    'VariableTypes', types, ...
    'VariableNames', names);
end
