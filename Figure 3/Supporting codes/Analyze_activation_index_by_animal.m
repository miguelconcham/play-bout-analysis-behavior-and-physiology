    for tt = 1:numel(type_names)
        for bb = 1:numel(behavior_names)
            original_curve = reshape(original(aa,tt,bb,:),1,n_time);
            recomputed_curve = reshape( ...
                recomputed(aa,tt,bb,:),1,n_time);
            valid = response_index & isfinite(original_curve) ...
                & isfinite(recomputed_curve);
            difference = recomputed_curve(valid)-original_curve(valid);
            if isempty(difference)
                mae = NaN;
                rmse = NaN;
                maximum = NaN;
                correlation = NaN;
                original_mean = NaN;
                recomputed_mean = NaN;
                sign_agreement = false;
            else
                mae = mean(abs(difference));
                rmse = sqrt(mean(difference.^2));
                maximum = max(abs(difference));
                original_valid = original_curve(valid);
                recomputed_valid = recomputed_curve(valid);
                original_mean = mean(original_valid);
                recomputed_mean = mean(recomputed_valid);
                sign_agreement = sign(original_mean) == ...
                    sign(recomputed_mean);
                if numel(difference) > 1 ...
                        && std(original_valid) > 0 ...
                        && std(recomputed_valid) > 0
                    correlation_matrix = corrcoef( ...
                        original_valid,recomputed_valid);
                    correlation = correlation_matrix(1,2);
                else
                    correlation = NaN;
                end
            end
            out_area(end+1,1) = area_names(aa); %#ok<AGROW>
            out_type(end+1,1) = type_names(tt); %#ok<AGROW>
            out_behavior(end+1,1) = behavior_names(bb); %#ok<AGROW>
            out_mae(end+1,1) = mae; %#ok<AGROW>
            out_rmse(end+1,1) = rmse; %#ok<AGROW>
            out_maximum(end+1,1) = maximum; %#ok<AGROW>
            out_correlation(end+1,1) = correlation; %#ok<AGROW>
            out_n_compared(end+1,1) = sum(valid); %#ok<AGROW>
            out_original_mean(end+1,1) = original_mean; %#ok<AGROW>
            out_recomputed_mean(end+1,1) = recomputed_mean; %#ok<AGROW>
            out_sign_agreement(end+1,1) = sign_agreement; %#ok<AGROW>
        end
    end
end
table_out = table(out_area,out_type,out_behavior,out_mae,out_rmse, ...
    out_maximum,out_correlation,out_n_compared,out_original_mean, ...
    out_recomputed_mean,out_sign_agreement, 'VariableNames', ...
    {'Area','CellType','Behavior','MeanAbsoluteDifference0to5s', ...
    'RMSE0to5s','MaximumAbsoluteDifference0to5s', ...
    'Correlation0to5s','NComparedTimepoints0to5s', ...
    'OriginalMean0to5s','RecomputedMean0to5s', ...
    'SignAgreement0to5s'});
end

