function contrasts = play_power_contrasts()
%PLAY_POWER_CONTRASTS  Paired autocorrelogram comparisons.
%
% side_b minus side_a is the difference tested along the autocorrelogram.
% For the power contrast that difference is high-power play minus
% low-power play. For the play contrasts it is play minus the
% power-matched time outside play.

contrasts = struct( ...
    'name', {'play_power', 'matched_power', 'matched_low', 'matched_high'}, ...
    'side_a', {'play_low', 'outside_matched', 'outside_low_matched', 'outside_high_matched'}, ...
    'side_b', {'play_high', 'play_matched', 'play_low_matched', 'play_high_matched'}, ...
    'side_a_label', { ...
        'Low-power play', ...
        'No play, matched power', ...
        'No play, low power', ...
        'No play, high power'}, ...
    'side_b_label', { ...
        'High-power play', ...
        'Play, matched power', ...
        'Play, low power', ...
        'Play, high power'}, ...
    'question', { ...
        'Play, different delta power', ...
        'Matched delta power, play versus no play', ...
        'Low delta power, play versus no play', ...
        'High delta power, play versus no play'});
end
